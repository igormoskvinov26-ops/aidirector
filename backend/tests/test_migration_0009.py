"""Миграция и модель должны описывать одни и те же колонки.

Расхождение здесь — это ошибка, которая не видна ни на одном тесте с
sqlite: тесты создают таблицы из моделей, а живая база строится миграцией.
Заметить её можно только на боевой установке, после обновления, когда
приложение уже не запускается.

Миграция здесь не выполняется — alembic нужен только внутри контейнера.
Сверяются имена колонок, объявленные в её тексте.
"""

import re
from pathlib import Path

from app.models.models import AppSetting, SettingsAudit

МИГРАЦИЯ = Path(__file__).resolve().parent.parent / "alembic" / "versions" / "0009_app_settings.py"


def _колонки_миграции(текст: str, таблица: str) -> set[str]:
    """Имена колонок из вызова create_table для нужной таблицы."""
    начало = текст.index(f"op.create_table(\n            {таблица},")
    # Конец вызова ищется по началу строки: внутри многострочного sa.Column
    # закрывающая скобка стоит с большим отступом и совпала бы как подстрока.
    конец = текст.index("\n        )", начало)
    кусок = текст[начало:конец]
    return set(re.findall(r'sa\.Column\(\s*"([a-z_]+)"', кусок))


def test_таблицы_совпадают_с_моделями():
    текст = МИГРАЦИЯ.read_text(encoding="utf-8")
    for модель, имя in ((AppSetting, "НАСТРОЙКИ"), (SettingsAudit, "ЖУРНАЛ")):
        из_миграции = _колонки_миграции(текст, имя)
        из_модели = {к.name for к in модель.__table__.columns}
        assert из_миграции == из_модели, (
            f"{модель.__tablename__}: в миграции {sorted(из_миграции)}, "
            f"в модели {sorted(из_модели)}"
        )


def test_миграция_продолжает_цепочку():
    """Оборванная цепочка означает, что на живой базе она просто не применится."""
    текст = МИГРАЦИЯ.read_text(encoding="utf-8")
    assert 'revision = "0009_app_settings"' in текст
    assert 'down_revision = "0008_telegram_settings"' in текст


def test_миграция_переносит_повторный_запуск():
    """Таблица может уже существовать: обновление накатывают и по второму разу."""
    текст = МИГРАЦИЯ.read_text(encoding="utf-8")
    assert "if not _существует(НАСТРОЙКИ):" in текст
    assert "if not _существует(ЖУРНАЛ):" in текст
