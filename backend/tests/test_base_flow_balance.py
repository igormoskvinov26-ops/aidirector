"""Баланс движения и Пульс базы должны сходиться (правка 16.10.2026).

До этого баланс считал отток «по последнему визиту внутри периода» и почти
всегда показывал плюс, пока пульс базы каждый день был в минусе.
"""

from datetime import date, timedelta

from app.services.client_base import LOST_AFTER_DAYS, base_flow, поток_клиента

СЕГОДНЯ = date(2026, 10, 16)
НАЧАЛО = date(2026, 10, 1)


def test_потерянный_считается_в_день_перехода_а_не_по_визиту():
    """Последний визит в августе, черта пройдена в октябре — это отток октября."""
    визит = НАЧАЛО - timedelta(days=LOST_AFTER_DAYS - 4)  # черта упадёт на 5 октября
    assert поток_клиента([визит], НАЧАЛО, СЕГОДНЯ) == {"new": 0, "returned": 0, "lost": 1}

    # Человек, который просто давно не ходит: черту прошёл в прошлом месяце.
    давно = НАЧАЛО - timedelta(days=200)
    assert поток_клиента([давно], НАЧАЛО, СЕГОДНЯ)["lost"] == 0


def test_новый_и_вернувшийся():
    assert поток_клиента([date(2026, 10, 5)], НАЧАЛО, СЕГОДНЯ)["new"] == 1
    ушёл = date(2026, 5, 1)
    вернулся = date(2026, 10, 7)
    итог = поток_клиента([ушёл, вернулся], НАЧАЛО, СЕГОДНЯ)
    assert итог == {"new": 0, "returned": 1, "lost": 0}  # потерян он был ещё летом


def test_баланс_периода_равен_сумме_пульсов():
    """Главная проверка: два блока на одной странице не должны спорить."""
    визиты = {
        1: [date(2026, 10, 3)],                                   # новый
        2: [НАЧАЛО - timedelta(days=LOST_AFTER_DAYS - 2)],        # уйдёт в потерянные
        3: [date(2026, 4, 1), date(2026, 10, 9)],                 # вернулся
        4: [date(2026, 9, 20), date(2026, 10, 10)],               # просто ходит
        5: [date(2026, 1, 5)],                                    # потерян давно
    }
    первый_известный = {cid: v[0] for cid, v in визиты.items()}
    пульс = base_flow(визиты, первый_известный, НАЧАЛО, СЕГОДНЯ)

    приход = отток = 0
    for v in визиты.values():
        п = поток_клиента(v, НАЧАЛО, СЕГОДНЯ)
        приход += п["new"] + п["returned"]
        отток += п["lost"]

    assert приход - отток == пульс["total"]
    assert (приход, отток) == (2, 1)
