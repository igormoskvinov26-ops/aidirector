"""Разбор конверта ответа YCLIENTS и устойчивость выгрузки.

Инцидент 28.09.2026: выгрузка встала на двое суток с сообщением
``'NoneType' object is not iterable``. Причина — запись ``result.get("data", [])``
по всему клиенту: пустой список она подставляет, только когда ключа `data`
НЕТ, а YCLIENTS при отказе присылает ключ со значением null. None уходил в
цикл записи в базу и ронял весь прогон, не называя ни адреса, ни шага.

Тесты ниже закрывают ровно эти случаи.
"""

from typing import Any

import pytest

from app.api.yclients import YclientsОтветНеПонят, данные_ответа
from app.services.sync import STAGES, непустой


# --------------------------------------------------------------------- #
# Конверт ответа
# --------------------------------------------------------------------- #


def test_null_в_data_даёт_пустой_список_а_не_none():
    """Главный случай инцидента: data есть, значение null."""
    assert данные_ответа({"success": True, "data": None}, "/staff") == []


def test_пустой_список_остаётся_пустым():
    assert данные_ответа({"success": True, "data": []}, "/staff") == []


def test_обычный_список_проходит_насквозь():
    строки = [{"id": 1}, {"id": 2}]
    assert данные_ответа({"success": True, "data": строки}, "/staff") == строки


def test_голый_список_без_конверта_проходит():
    строки = [{"id": 7}]
    assert данные_ответа(строки, "/services") == строки


def test_одиночный_объект_заворачивается_в_список():
    """Часть адресов отдаёт объект вместо набора — содержимое терять нельзя."""
    assert данные_ответа({"data": {"id": 3}}, "/schedule") == [{"id": 3}]


def test_отказ_адреса_поднимает_ошибку_а_не_ноль():
    """success: false — это отказ, и он не должен выглядеть как «нет данных»."""
    with pytest.raises(YclientsОтветНеПонят, match="отказ"):
        данные_ответа({"success": False, "data": None}, "/company/1/staff")


def test_причина_отказа_попадает_в_текст():
    with pytest.raises(YclientsОтветНеПонят, match="Неверный токен"):
        данные_ответа(
            {"success": False, "data": None, "meta": {"message": "Неверный токен"}},
            "/company/1/staff",
        )


def test_адрес_есть_в_тексте_ошибки():
    """По сообщению должно быть видно, какой именно адрес подвёл."""
    with pytest.raises(YclientsОтветНеПонят, match="/company/19164/staff"):
        данные_ответа({"success": False}, "/company/19164/staff")


@pytest.mark.parametrize("мусор", ["строка", 42, None])
def test_ответ_неожиданного_типа_поднимает_ошибку(мусор: Any):
    with pytest.raises(YclientsОтветНеПонят):
        данные_ответа(мусор, "/staff")


def test_data_неожиданного_типа_поднимает_ошибку():
    with pytest.raises(YclientsОтветНеПонят, match="ожидался список"):
        данные_ответа({"data": "не список"}, "/staff")


# --------------------------------------------------------------------- #
# Пустой справочник = отказ, а не «ничего не изменилось»
# --------------------------------------------------------------------- #


def test_пустые_сотрудники_это_ошибка():
    """У работающего барбершопа не бывает ноль сотрудников."""
    with pytest.raises(RuntimeError, match="пустой список"):
        непустой("сотрудники", [])


def test_текст_подсказывает_про_токен():
    with pytest.raises(RuntimeError, match="токен"):
        непустой("услуги", [])


def test_непустой_справочник_проходит_молча():
    непустой("сотрудники", [{"id": 1, "name": "Арташ"}])


# --------------------------------------------------------------------- #
# Шаги выгрузки названы по-русски — иначе ошибку нельзя прочитать
# --------------------------------------------------------------------- #


def test_у_каждого_шага_есть_русское_имя():
    for шаг in ("staff", "services", "clients", "visits", "sales"):
        assert STAGES.get(шаг), f"шаг {шаг} без названия"
