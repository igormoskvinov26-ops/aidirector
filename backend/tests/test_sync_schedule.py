"""Расписание выгрузки переживает сон компьютера (случай салона 19.10.2026).

Длинный asyncio.sleep отмеряет время монотонными часами, а они в контейнере
замирают, пока Windows спит. Салонный Пульт заснул в 20:50 с начатым часом,
утром досчитал его остаток и за ночь не выгрузил ничего — в интерфейсе при
этом не было ошибки, только старая дата. Поэтому срок проверяется по
настенным часам.
"""

from datetime import UTC, datetime, timedelta

import pytest

from app.services import sync


def test_срок_проверяется_по_настенным_часам():
    следующий = datetime(2026, 10, 18, 21, 50, tzinfo=UTC)
    assert not sync.пора_выгружать(следующий, следующий - timedelta(minutes=1))
    assert sync.пора_выгружать(следующий, следующий)
    # Компьютер проспал ночь: срок давно прошёл, выгрузка должна пойти сразу.
    assert sync.пора_выгружать(следующий, следующий + timedelta(hours=13))


def test_шаг_ожидания_не_длиннее_минуты():
    """После пробуждения ждать выгрузку дольше минуты никто не должен."""
    assert 0 < sync.ШАГ_ОЖИДАНИЯ <= 60


def test_после_сна_срок_просрочен_и_пауза_короткая():
    """Что делает цикл: ждёт короткими отрезками и сверяется с часами.

    Длинный сон заменён на min(ШАГ_ОЖИДАНИЯ, остаток) — значит после
    пробуждения компьютера между «проснулись» и «выгрузили» проходит не
    больше минуты, сколько бы часов ни длился сон.
    """
    уснули = datetime(2026, 10, 18, 20, 50, tzinfo=UTC)
    следующий = уснули + timedelta(minutes=60)
    проснулись = уснули + timedelta(hours=13)

    остаток = (следующий - уснули).total_seconds()
    assert min(sync.ШАГ_ОЖИДАНИЯ, остаток) <= 60  # спим отрезком, не часом
    assert sync.пора_выгружать(следующий, проснулись)
