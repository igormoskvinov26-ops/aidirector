"""Дашборд месяца по мастерам: выполнено, впереди, прогноз.

Владелец описал его так: строки — мастера, столбцы двумя блоками, плюс строка
итогов по всем и столбец прогноза, складывающий выполненное с будущим. Здесь
закреплена арифметика этих сумм — та, на которую он будет смотреть, решая,
хватает ли до плана.
"""

import pytest

from app.api.routes.barber_month import _expected, _totals, _вклад

# Числа те же, что в test_payroll_scope: один набор на два представления одних
# и тех же данных, чтобы расхождение между ними было видно сразу.
КСЕНИЯ = {
    "staff_id": 5659614, "name": "Ксения", "completed_count": 40,
    "completed_revenue": 120000, "future_count": 12, "future_revenue": 30000,
    "product_sales": 5000,
}
АРТАШ = {
    "staff_id": 5659611, "name": "Арташ", "completed_count": 55,
    "completed_revenue": 180000, "future_count": 18, "future_revenue": 45000,
    "product_sales": 7000,
}
ДМИТРИЙ = {
    "staff_id": 5659617, "name": "Дмитрий", "completed_count": 30,
    "completed_revenue": 90000, "future_count": 9, "future_revenue": 22000,
    "product_sales": 3000,
}
ВСЕ = [КСЕНИЯ, АРТАШ, ДМИТРИЙ]


# --------------------------------------------------------------------------- #
# Столбец прогноза по мастеру
# --------------------------------------------------------------------------- #


def test_прогноз_записей_складывает_выполненные_и_будущие():
    assert _expected(КСЕНИЯ)["expected_count"] == 52


def test_прогноз_услуг_без_косметики():
    """120 000 выполненных услуг + 30 000 будущих = 150 000. Косметика сюда
    не входит: этот столбец про то, чем мастер управляет расписанием."""
    assert _expected(КСЕНИЯ)["expected_services"] == 150000.0


def test_прогноз_с_косметикой_добавляет_продажи():
    """150 000 услуг + 5 000 косметики = 155 000."""
    assert _expected(КСЕНИЯ)["expected_revenue"] == 155000.0


def test_два_столбца_различаются_ровно_на_косметику():
    прогноз = _expected(КСЕНИЯ)
    разница = прогноз["expected_revenue"] - прогноз["expected_services"]
    assert разница == pytest.approx(float(КСЕНИЯ["product_sales"]))


def test_без_данных_о_косметике_услуги_всё_равно_считаются():
    """Главная причина разделить столбцы: косметика приходит отдельным ответом
    YCLIENTS, который может и не прийти. Прогноз по услугам от этого не должен
    исчезать — иначе дашборд пустеет из-за второстепенных данных."""
    без_косметики = {**КСЕНИЯ, "product_sales": None}
    прогноз = _expected(без_косметики)
    assert прогноз["expected_services"] == 150000.0
    assert прогноз["expected_count"] == 52
    # А вот сумма с косметикой не показывается: ноль вместо неизвестного
    # выглядел бы как настоящая сумма.
    assert прогноз["expected_revenue"] is None


def test_пустая_строка_не_роняет_расчёт():
    """Ни одного поля — считать нечего, но и падать не должно.

    Услуги и записи честно нулевые. Сумма с косметикой — «неизвестно», а не
    ноль: отсутствующая косметика это отсутствие данных, а не нулевые продажи.
    """
    assert _expected({}) == {
        "expected_count": 0,
        "expected_services": 0.0,
        "expected_revenue": None,
    }


# --------------------------------------------------------------------------- #
# Строка итогов
# --------------------------------------------------------------------------- #


def test_итог_складывает_каждый_столбец_по_всем_мастерам():
    итог = _totals(ВСЕ)
    assert итог["completed_count"] == 125
    assert итог["completed_revenue"] == 390000.0
    assert итог["future_count"] == 39
    assert итог["future_revenue"] == 97000.0
    assert итог["product_sales"] == 15000.0


@pytest.mark.parametrize("поле", ["expected_services", "expected_revenue"])
def test_прогноз_итога_совпадает_с_суммой_прогнозов_по_мастерам(поле):
    """Иначе строка итогов противоречит строкам над ней, и верить нельзя ни
    той, ни другим. Проверяются оба столбца суммы."""
    по_мастерам = sum(_expected(m)[поле] for m in ВСЕ)
    итог = _totals(ВСЕ)
    assert _expected(итог)[поле] == pytest.approx(по_мастерам)


def test_прогноз_записей_в_итоге_тоже_совпадает():
    по_мастерам = sum(_expected(m)["expected_count"] for m in ВСЕ)
    assert _expected(_totals(ВСЕ))["expected_count"] == по_мастерам


def test_итог_по_одному_мастеру_равен_его_строке():
    """Мастер видит свою строку и итог под ней. Разойтись они не могут."""
    итог = _totals([АРТАШ])
    assert итог["completed_count"] == АРТАШ["completed_count"]
    assert итог["future_revenue"] == float(АРТАШ["future_revenue"])
    assert _expected(итог) == _expected(АРТАШ)


def test_итог_без_мастеров_это_нули_а_не_ошибка():
    итог = _totals([])
    assert итог["completed_count"] == 0
    assert итог["future_revenue"] == 0.0


# --------------------------------------------------------------------------- #
# Вклад мастера: выручка минус его зарплата
#
# Владелец назвал это «чистой прибылью» и назвал самым важным числом. Чистой
# прибылью салона оно не является, и путать их нельзя: постоянные расходы —
# 389 117 ₽ в месяц, — расходники и эквайринг сюда не входят, они не делятся
# по мастерам. Здесь закреплена именно та арифметика, что показана на экране.
# --------------------------------------------------------------------------- #


С_ЗАРПЛАТОЙ = {**КСЕНИЯ, "earned": 51360}


def test_вклад_это_выручка_минус_зарплата():
    """120 000 услуг + 5 000 косметики − 51 360 зарплаты = 73 640."""
    assert _вклад(С_ЗАРПЛАТОЙ)["contribution"] == 73640.0


def test_будущие_записи_во_вклад_не_входят():
    """Их ещё не оплатили. Иначе вклад считался бы по деньгам, которых нет."""
    без_будущих = {**С_ЗАРПЛАТОЙ, "future_revenue": 0}
    assert _вклад(без_будущих)["contribution"] == _вклад(С_ЗАРПЛАТОЙ)["contribution"]


def test_зарплата_отдаётся_как_есть():
    assert _вклад(С_ЗАРПЛАТОЙ)["payroll"] == 51360.0


def test_без_зарплаты_вклад_не_считается():
    """Выручка без вычета зарплаты выглядела бы как вклад и завышала бы его
    на десятки тысяч."""
    итог = _вклад({**КСЕНИЯ, "earned": None})
    assert итог["contribution"] is None
    assert итог["payroll"] is None


def test_без_косметики_вклад_не_считается():
    """Косметика входит в выручку мастера. Без неё вклад занижен."""
    assert _вклад({**С_ЗАРПЛАТОЙ, "product_sales": None})["contribution"] is None


def test_вклад_может_быть_отрицательным():
    """Мастер на гаранте при пустом месяце обходится салону дороже, чем
    приносит. Прятать это нельзя — ради этого столбец и заведён."""
    слабый = {**КСЕНИЯ, "completed_revenue": 9000, "product_sales": 0, "earned": 24000}
    assert _вклад(слабый)["contribution"] == -15000.0


# --------------------------------------------------------------------------- #
# Порядок строк
#
# По прогнозу выручки с косметикой, от большего. Владелец 18.09.2026: это
# ключевой параметр, по нему он сравнивает мастеров.
# --------------------------------------------------------------------------- #


class ЗапросБезРоли:
    """Подделка запроса: роль владельца, привязки к мастеру нет."""

    class state:  # noqa: N801  — имя как у настоящего request.state
        role = "owner"
        staff_id = None


async def _порядок(monkeypatch, мастера):
    from app.api.routes import barber_month

    async def отчёт():
        return {"masters": мастера, "warnings": [], "month_start": "2026-09-01",
                "month_end": "2026-09-30", "as_of": "", "updated_at": ""}

    monkeypatch.setattr(barber_month, "report", отчёт)
    ответ = await barber_month.future(ЗапросБезРоли())
    return [м["name"] for м in ответ["masters"]]


@pytest.mark.asyncio
async def test_мастера_идут_по_убыванию_прогноза(monkeypatch):
    порядок = await _порядок(monkeypatch, [КСЕНИЯ, ДМИТРИЙ, АРТАШ])
    # Ксения 155 000, Арташ 232 000, Дмитрий 115 000.
    assert порядок == ["Арташ", "Ксения", "Дмитрий"]


@pytest.mark.asyncio
async def test_строка_без_косметики_не_улетает_в_конец(monkeypatch):
    """У неё нет прогноза с косметикой, но по услугам мастер первый. Сортировка
    по отсутствующему числу отправила бы его вниз, и владелец решил бы, что
    он работает хуже всех."""
    лидер = {**АРТАШ, "product_sales": None, "name": "Арташ"}
    порядок = await _порядок(monkeypatch, [КСЕНИЯ, лидер, ДМИТРИЙ])
    assert порядок[0] == "Арташ"
