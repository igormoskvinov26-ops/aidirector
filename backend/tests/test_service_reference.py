"""Визит не должен ссылаться на услугу, которой нет в нашей базе.

YCLIENTS отдаёт действующие услуги, а визиты за прошедшие месяцы ссылаются и
на удалённые. Прежде для такой услуги подставлялся её идентификатор из
YCLIENTS — чужое для нашей базы число. На живой установке 17.09.2026 это
уронило всю выгрузку визитов: 2441 запись приехала, не сохранилась ни одна,
ForeignKeyViolationError на visit_services_service_id_fkey.

Вторая, более тихая беда того же места: совпади подставленное число с
существующей строкой услуг, визит приписался бы не к той услуге — молча, и
дальше это ушло бы в расчёт зарплаты.
"""

import pytest

from app.repositories.repositories import _услуга_под_ссылку


class ПоддельнаяСтрока:
    def __init__(self, значение):
        self._значение = значение

    def __getitem__(self, индекс):
        assert индекс == 0
        return self._значение


class ПоддельныйОтвет:
    def __init__(self, значение):
        self._значение = значение

    def fetchone(self):
        return None if self._значение is None else ПоддельнаяСтрока(self._значение)


class ПоддельнаяСессия:
    """Записывает, что от неё просили, и отдаёт заранее заданный id."""

    def __init__(self, выдаваемый_id=777):
        self.запросы = []
        self._id = выдаваемый_id

    async def execute(self, stmt):
        self.запросы.append(stmt)
        return ПоддельныйОтвет(self._id)


@pytest.mark.asyncio
async def test_известная_услуга_берётся_из_карты():
    """Ничего не вставляем: услуга есть, её локальный номер известен."""
    сессия = ПоддельнаяСессия()
    карта = {555: 42}
    результат = await _услуга_под_ссылку(сессия, карта, {"id": 555, "title": "Стрижка"})
    assert результат == 42
    assert сессия.запросы == []


@pytest.mark.asyncio
async def test_незнакомая_услуга_заводится_заместителем():
    сессия = ПоддельнаяСессия(выдаваемый_id=777)
    карта = {}
    результат = await _услуга_под_ссылку(
        сессия, карта, {"id": 999, "title": "Стрижка машинкой"}
    )
    assert результат == 777
    assert len(сессия.запросы) == 1


@pytest.mark.asyncio
async def test_номер_yclients_никогда_не_идёт_в_ссылку():
    """Главное в этой правке. Прежде возвращалось 999 — номер из YCLIENTS."""
    сессия = ПоддельнаяСессия(выдаваемый_id=777)
    результат = await _услуга_под_ссылку(сессия, {}, {"id": 999, "title": "Бритьё"})
    assert результат != 999


@pytest.mark.asyncio
async def test_заместитель_помечен_неактивным():
    """Это не услуга прейскуранта, а след удалённой: в списке ей не место."""
    сессия = ПоддельнаяСессия()
    await _услуга_под_ссылку(сессия, {}, {"id": 999, "title": "Окантовка"})
    значения = сессия.запросы[0].compile().params
    assert значения["is_active"] is False
    assert значения["yclients_id"] == 999
    assert значения["title"] == "Окантовка"


@pytest.mark.asyncio
async def test_услуга_без_названия_получает_понятное():
    сессия = ПоддельнаяСессия()
    await _услуга_под_ссылку(сессия, {}, {"id": 999, "title": ""})
    assert сессия.запросы[0].compile().params["title"] == "Услуга удалена в YCLIENTS"


@pytest.mark.asyncio
async def test_длинное_название_обрезается_до_поля():
    """В базе поле на 255 символов. Длиннее — отказ и снова потерянная выгрузка."""
    сессия = ПоддельнаяСессия()
    await _услуга_под_ссылку(сессия, {}, {"id": 999, "title": "щ" * 400})
    assert len(сессия.запросы[0].compile().params["title"]) == 255


@pytest.mark.asyncio
async def test_строка_без_идентификатора_пропускается():
    """Заводить заместителя не на что: связать его будет не с чем."""
    сессия = ПоддельнаяСессия()
    assert await _услуга_под_ссылку(сессия, {}, {"title": "без номера"}) is None
    assert await _услуга_под_ссылку(сессия, {}, {"id": 0, "title": "нулевой"}) is None
    assert сессия.запросы == []


@pytest.mark.asyncio
async def test_заместитель_заводится_один_раз_на_выгрузку():
    """Одна и та же удалённая услуга встречается во многих визитах."""
    сессия = ПоддельнаяСессия(выдаваемый_id=777)
    карта = {}
    for _ in range(5):
        assert await _услуга_под_ссылку(сессия, карта, {"id": 999, "title": "Бритьё"}) == 777
    assert len(сессия.запросы) == 1
    assert карта == {999: 777}


@pytest.mark.asyncio
async def test_если_база_ничего_не_вернула_ссылки_нет():
    сессия = ПоддельнаяСессия(выдаваемый_id=None)
    assert await _услуга_под_ссылку(сессия, {}, {"id": 999, "title": "Стрижка"}) is None
