"""Учётные записи для входа, заведённые через мастер первичной настройки.

Раньше логины и пароли можно было задать только в .env. На свежей установке
это означало тупик: чтобы открыть Пульта, нужен пароль, а чтобы его
задать — доступ к файлу на сервере. Теперь при пустом владельце приложение
поднимается в режиме настройки, и владелец заводит себе учётную запись прямо
в браузере.

Пароль хранится не как есть, а хешем PBKDF2-HMAC-SHA256 — в отличие от .env,
куда он ложится открытым текстом. Своей криптографии здесь нет: алгоритм из
стандартной библиотеки, соль случайная, число проходов записано рядом с
хешем, чтобы его можно было поднять, не ломая уже заведённые записи.

Значения из .env остаются в силе и проверяются первыми: у развёрнутых
установок они уже настроены, и молча перестать их принимать нельзя.
"""

from __future__ import annotations

import hashlib
import hmac
import os
import secrets

from loguru import logger
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import MIN_PASSWORD, _is_known_weak
from app.models.models import AppSetting

# Проходов PBKDF2. Вход происходит десятки раз в день, не тысячи, поэтому
# берём с запасом: задержка в сотую долю секунды человеку незаметна, а
# перебору украденной базы мешает ощутимо.
ПРОХОДОВ = 480_000
МИН_ДЛИНА = MIN_PASSWORD

# "top" — Владелец: одна запись на все филиалы, хранится в базе главного.
# Пока её нет, Владельцем считается главный вход (owner) — иначе завести её
# было бы некому. Как только заведена, главный вход становится Управляющим.
ЛОГИН = {"owner": "OWNER_LOGIN", "operator": "OPERATOR_LOGIN", "top": "TOP_LOGIN"}
ПАРОЛЬ = {"owner": "OWNER_PASSWORD_HASH", "operator": "OPERATOR_PASSWORD_HASH", "top": "TOP_PASSWORD_HASH"}
НАШИ_КЛЮЧИ = set(ЛОГИН.values()) | set(ПАРОЛЬ.values())

# Кэш процесса: проверка пароля идёт в middleware на каждый запрос, и ходить
# за ней в базу каждый раз незачем. Обновляется при старте и при заведении.
_учётные: dict[str, str] = {}
# Учётные записи активного филиала (не главного): управляющий и администратор
# этого филиала. Главные (_учётные) остаются от владельца и от переключения не зависят.
_ветка: dict[str, str] = {}


def _хеш(пароль: str, соль: bytes | None = None) -> str:
    соль = соль or os.urandom(16)
    отпечаток = hashlib.pbkdf2_hmac("sha256", пароль.encode("utf-8"), соль, ПРОХОДОВ)
    return f"pbkdf2_sha256${ПРОХОДОВ}${соль.hex()}${отпечаток.hex()}"


def _совпадает(пароль: str, запись: str) -> bool:
    """Сверка пароля с сохранённым хешем. Непонятная запись — не совпадение."""
    try:
        метод, проходов, соль, отпечаток = запись.split("$")
        if метод != "pbkdf2_sha256":
            return False
        свой = hashlib.pbkdf2_hmac(
            "sha256", пароль.encode("utf-8"), bytes.fromhex(соль), int(проходов)
        )
    except (ValueError, TypeError):
        logger.warning("сохранённый пароль записан в непонятном виде")
        return False
    return hmac.compare_digest(свой.hex(), отпечаток)


async def загрузить(session: AsyncSession) -> None:
    """Перечитать учётные записи из базы в кэш процесса."""
    строки = (
        (await session.execute(select(AppSetting).where(AppSetting.key.in_(НАШИ_КЛЮЧИ))))
        .scalars()
        .all()
    )
    _учётные.clear()
    for строка in строки:
        if строка.value:
            _учётные[строка.key] = строка.value


async def загрузить_ветку(session: AsyncSession | None) -> None:
    """Учётные записи филиала. None — активен главный филиал, своих нет."""
    _ветка.clear()
    if session is None:
        return
    строки = (
        (await session.execute(select(AppSetting).where(AppSetting.key.in_(НАШИ_КЛЮЧИ))))
        .scalars()
        .all()
    )
    for строка in строки:
        if строка.value:
            _ветка[строка.key] = строка.value


def заведён(роль: str) -> bool:
    return bool(_учётные.get(ЛОГИН[роль]) and _учётные.get(ПАРОЛЬ[роль]))


def логин(роль: str) -> str:
    return _учётные.get(ЛОГИН[роль], "")


def проверить_пароль(роль: str, логин_: str, пароль: str, ветка: bool = False) -> bool:
    """Подходит ли пара к заведённой через мастер учётной записи этой роли.

    ветка=True — к записи активного не главного филиала, иначе к главной."""
    кэш = _ветка if ветка else _учётные
    сохранённый_логин = кэш.get(ЛОГИН[роль])
    сохранённый_хеш = кэш.get(ПАРОЛЬ[роль])
    if not сохранённый_логин or not сохранённый_хеш:
        return False
    # Сверяем пароль всегда, даже при чужом логине: иначе по времени ответа
    # видно, существует ли такая учётная запись.
    пароль_подходит = _совпадает(пароль, сохранённый_хеш)
    логин_подходит = hmac.compare_digest(
        логин_.encode("utf-8"), сохранённый_логин.encode("utf-8")
    )
    return логин_подходит and пароль_подходит


def проверить_требования(логин_: str, пароль: str) -> None:
    """Те же требования, что и к паролям из .env. Поднимает ValueError."""
    if not логин_.strip():
        raise ValueError("Логин не может быть пустым")
    if len(пароль) < МИН_ДЛИНА:
        raise ValueError(f"Пароль должен быть не короче {МИН_ДЛИНА} символов")
    if _is_known_weak(пароль):
        raise ValueError(
            "Этот пароль есть в списке заведомо слабых — придумайте другой"
        )


async def завести(
    session: AsyncSession, роль: str, логин_: str, пароль: str, ветка: bool = False
) -> None:
    """Создать или сменить учётную запись роли. Пароль в базу идёт хешем."""
    if роль not in ЛОГИН:
        raise ValueError(f"Неизвестная роль: {роль}")
    проверить_требования(логин_, пароль)

    for ключ, значение in ((ЛОГИН[роль], логин_.strip()), (ПАРОЛЬ[роль], _хеш(пароль))):
        строка = await session.get(AppSetting, ключ)
        if строка is None:
            session.add(AppSetting(key=ключ, value=значение, updated_by=роль))
        else:
            строка.value = значение
            строка.updated_by = роль
    await session.commit()
    await (загрузить_ветку(session) if ветка else загрузить(session))
    # Ни логин, ни пароль в журнал не идут.
    logger.info(f"заведена учётная запись роли {роль}")


# ── Код первичной настройки ───────────────────────────────────────────────

# Пока владелец не заведён, мастер настройки открыт без пароля — паролю
# просто неоткуда взяться. Чтобы этим не воспользовался кто-то другой,
# мастер спрашивает короткий код, который печатается в окне установки и
# кладётся в файл рядом с журналом. У человека, который ставит программу,
# он перед глазами; у постороннего — нет.
_код: str = ""


def код_настройки() -> str:
    return _код


def выдать_код_настройки() -> str:
    """Сгенерировать код на этот запуск. Вызывается при старте."""
    global _код
    _код = secrets.token_hex(3).upper()  # шесть знаков — набирается руками
    return _код


def код_подходит(введено: str) -> bool:
    if not _код:
        return False
    return hmac.compare_digest(введено.strip().upper().encode(), _код.encode())
