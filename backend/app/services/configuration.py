# ── Описание того, что вообще настраивается ───────────────────────────────


@dataclass(frozen=True)
class Ключ:
    """Одна настройка: как называется в .env и как показывается человеку."""

    имя: str
    заголовок: str
    # Поле пароля: не возвращается целиком никогда, показывается маской.
    секрет: bool = False
    # Без него интеграция не работает.
    обязательный: bool = True
    # number — в интерфейсе числовое поле, при чтении приводится к int.
    вид: str = "text"
    подсказка: str = ""


@dataclass(frozen=True)
class Интеграция:
    """Набор ключей, которые имеют смысл только вместе."""

    ид: str
    название: str
    описание: str
    ключи: tuple[Ключ, ...]
    # Ядро приложения. Без YCLIENTS нет данных вообще; без Telegram не
    # работает только отправка, и это не повод гасить аналитику.
    критичная: bool = False
    # Новое значение подхватывается работающим процессом без перезапуска.
    # Сейчас так у обеих: ключи читаются на каждый запрос к сервису, а не
    # один раз при старте. Поле заведено не впрок — у банка и эквайринга
    # может оказаться иначе, и тогда интерфейс обязан честно сказать, что
    # без перезапуска настройка не применится (ТЗ, раздел 11).
    применяется_сразу: bool = True

    @property
    def обязательные(self) -> tuple[Ключ, ...]:
        return tuple(к for к in self.ключи if к.обязательный)


