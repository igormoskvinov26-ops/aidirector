# ── Журнал изменений ──────────────────────────────────────────────────────


async def журнал(session: AsyncSession, предел: int = 50) -> list[dict[str, Any]]:
    строки = (
        (
            await session.execute(
                select(SettingsAudit).order_by(SettingsAudit.at.desc()).limit(предел)
            )
        )
        .scalars()
        .all()
    )
    return [
        {
            "at": строка.at.isoformat() if isinstance(строка.at, datetime) else None,
            "who": строка.who,
            "integration": строка.integration,
            "key": строка.key,
            "action": строка.action,
        }
        for строка in строки
    ]
