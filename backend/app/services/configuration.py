"""Единое место, где Пульт узнаёт ключи интеграций.

До этого ключи YCLIENTS жили только в .env на сервере. Владелец без доступа
к серверу не мог ни сменить отозванный токен, ни понять, почему перестало
обновляться: приложение просто не запускалось, а причина оставалась в
трейсбеке внутри контейнера. Теперь ключи настраиваются в разделе
«Настройки → Интеграции», а .env остаётся запасным вариантом.

Приоритет источников:

    переменная окружения процесса  >  таблица app_settings  >  файл .env  >  пусто

Первое — потому что заданное инфраструктурой (docker-compose, systemd, панель
хостинга) веб-интерфейс перекрыть не может: при следующем перезапуске
вернётся значение инфраструктуры, а человек будет смотреть на настройку,
которая «не применяется». Такие ключи показываются только для чтения.

Второе выше третьего сознательно: так уже работает настройка Telegram
(решение владельца 27.09.2026), и менять это направление означало бы, что у
части установок молча вернутся старые значения из .env.

Значения читаются через кэш в памяти процесса, а не запросом к базе на
каждое обращение: за ключами ходит в том числе выгрузка, для которой сессии
базы под рукой нет. Кэш обновляется при старте и после каждого сохранения.
"""

