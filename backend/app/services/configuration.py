# ── Источники значений ────────────────────────────────────────────────────

# Ключ .env → имя поля в Settings. Нужен, чтобы прочитать то, что пришло из
# файла, не парся файл заново.
ПОЛЕ_НАСТРОЕК: dict[str, str] = {имя: имя.lower() for имя in ВСЕ_КЛЮЧИ}

# Управляемые значения из базы. Пустой словарь = «ещё не читали».
_управляемые: dict[str, str] = {}
_загружено = False

# Последняя неудачная проверка связи по интеграции. В базе не хранится: это
# состояние текущего процесса, а не настройка.
_последняя_ошибка: dict[str, str] = {}


# Филиал не главный: ключи доступа и номер компании берутся только из его базы.
# Иначе у нового филиала молча остались бы токены главного из .env.
ИЗОЛИРОВАННЫЕ = {"YCLIENTS_COMPANY_ID", "YCLIENTS_USER_TOKEN", "HUB_TOKEN",
                 "TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID"}
изолирован = False


def _из_файла(имя: str) -> str:
    """Значение из .env (или из умолчания в Settings), строкой."""
    if изолирован and имя in ИЗОЛИРОВАННЫЕ:
        return ""
    поле = ПОЛЕ_НАСТРОЕК.get(имя)
    if поле is None:
        return ""
    значение = getattr(settings, поле, "")
    if значение in (None, 0):
        return ""
    return str(значение)


def задано_инфраструктурой(имя: str) -> bool:
    """Ключ пришёл настоящей переменной окружения — веб его менять не вправе."""
    return имя in ИЗ_ОКРУЖЕНИЯ_ПРОЦЕССА and bool(_из_файла(имя))


def источник(имя: str) -> str:
    """Откуда взято действующее значение: process_env | managed | env_file | none."""
    if задано_инфраструктурой(имя):
        return "process_env"
    if _управляемые.get(имя):
        return "managed"
    if _из_файла(имя):
        return "env_file"
    return "none"


def значение(имя: str) -> str:
    """Действующее значение ключа по приоритету источников."""
    if задано_инфраструктурой(имя):
        return _из_файла(имя)
    управляемое = _управляемые.get(имя)
    if управляемое:
        return управляемое
    return _из_файла(имя)


def число(имя: str) -> int:
    """То же, но числом. Мусор в поле не должен ронять вызывающий код."""
    try:
        return int(str(значение(имя)).strip() or 0)
    except ValueError:
        logger.warning(f"{имя}: значение не похоже на число, считаю ненастроенным")
        return 0


def настроена(ид: str) -> bool:
    """Все обязательные ключи интеграции заполнены."""
    интеграция = ПО_ИД.get(ид)
    if интеграция is None:
        return False
    return all(значение(к.имя) for к in интеграция.обязательные)


# ── Загрузка и сохранение ─────────────────────────────────────────────────


async def загрузить(session: AsyncSession) -> None:
    """Прочитать управляемые настройки в кэш процесса.

    Вызывается при старте и после каждого изменения. Отдельно от чтения
    значений: за ними ходят из мест, где сессии базы нет.
    """
    global _загружено
    строки = (await session.execute(select(AppSetting))).scalars().all()
    _управляемые.clear()
    for строка in строки:
        if строка.value:
            _управляемые[строка.key] = строка.value
    await _прочитать_телеграм(session)
    _загружено = True
    logger.info(f"управляемых настроек в базе: {len(_управляемые)}")


# Ключи, которые хранятся не в app_settings, а в своей таблице. Telegram
# настраивался через интерфейс ещё до этой доработки (решение владельца
# 27.09.2026), и у него есть своё место хранения вместе с именем бота и
# названием чата. Заводить для тех же двух значений второе место означало бы
# ровно одно: рано или поздно они разойдутся, и никто не скажет, какое верное.
ТЕЛЕГРАМ_ТОКЕН = "TELEGRAM_BOT_TOKEN"
ТЕЛЕГРАМ_ЧАТ = "TELEGRAM_CHAT_ID"
СВОЁ_ХРАНИЛИЩЕ = {ТЕЛЕГРАМ_ТОКЕН, ТЕЛЕГРАМ_ЧАТ}


async def _прочитать_телеграм(session: AsyncSession) -> None:
    """Бот и чат — из таблицы telegram_settings, она для них хранилище."""
    try:
        from app.services import telegram_settings

        строка = await telegram_settings.получить(session)
    except Exception as сбой:  # noqa: BLE001 — таблицы может не быть на старой базе
        logger.debug(f"настройки Telegram не прочитаны: {сбой}")
        return
    if строка is None:
        return
    if строка.bot_token:
        _управляемые[ТЕЛЕГРАМ_ТОКЕН] = строка.bot_token
    if строка.chat_id:
        _управляемые[ТЕЛЕГРАМ_ЧАТ] = строка.chat_id


async def _сохранить_телеграм(session: AsyncSession, токен: str, чат: str) -> None:
    """Запись в родное хранилище Telegram, с сохранением того, что уже было.

    Владелец может менять только chat_id — тогда токен берётся прежний, и
    наоборот. Без этого правка одного поля стирала бы второе.
    """
    from app.services import telegram_settings

    прежнее = await telegram_settings.получить(session)
    await telegram_settings.сохранить(
        session,
        bot_token=токен or (прежнее.bot_token if прежнее else ""),
        chat_id=чат or (прежнее.chat_id if прежнее else ""),
        bot_username=прежнее.bot_username if прежнее else None,
        chat_title=прежнее.chat_title if прежнее else None,
    )


async def сохранить(
    session: AsyncSession, значения: dict[str, str], кто: str
) -> list[str]:
    """Записать управляемые значения. Возвращает имена ключей, которые изменились.

    Пустая строка означает «не трогать», а не «стереть»: форма присылает
    незаполненные поля пустыми, и иначе редактирование chat_id стирало бы
    токен бота. Для стирания есть отдельное действие — `сбросить`.
    """
    изменены: list[str] = []
    телеграм: dict[str, str] = {}

    for имя, новое in значения.items():
        ключ = ВСЕ_КЛЮЧИ.get(имя)
        if ключ is None:
            logger.warning(f"настройка {имя} не используется Пультом — пропускаю")
            continue
        новое = (новое or "").strip()
        if not новое:
            continue
        if задано_инфраструктурой(имя):
            logger.warning(f"{имя} задан переменной окружения — из интерфейса не меняется")
            continue
        if новое == значение(имя):
            continue

        if имя in СВОЁ_ХРАНИЛИЩЕ:
            телеграм[имя] = новое
            session.add(
                SettingsAudit(
                    who=кто,
                    integration=ИНТЕГРАЦИЯ_КЛЮЧА.get(имя, "?"),
                    key=имя,
                    action="changed",
                )
            )
            изменены.append(имя)
            continue

        строка = await session.get(AppSetting, имя)
        if строка is None:
            строка = AppSetting(key=имя, value=новое, updated_by=кто)
            session.add(строка)
        else:
            строка.value = новое
            строка.updated_by = кто
        session.add(
            SettingsAudit(
                who=кто,
                integration=ИНТЕГРАЦИЯ_КЛЮЧА.get(имя, "?"),
                key=имя,
                action="changed",
            )
        )
        изменены.append(имя)

    if изменены:
        if телеграм:
            # Внутри — свой commit: хранилище Telegram живёт отдельной строкой,
            # и записывать его надо до общего перечитывания кэша.
            await _сохранить_телеграм(
                session,
                телеграм.get(ТЕЛЕГРАМ_ТОКЕН, ""),
                телеграм.get(ТЕЛЕГРАМ_ЧАТ, ""),
            )
        await session.commit()
        await загрузить(session)
        _забыть_ошибки({ИНТЕГРАЦИЯ_КЛЮЧА.get(и, "") for и in изменены})
        _сбросить_кэш_клиентов()
        # Само значение в журнал не идёт — только имя ключа.
        logger.info(f"настройки изменены ({кто}): {', '.join(изменены)}")
    return изменены


async def сбросить(session: AsyncSession, имя: str, кто: str) -> None:
    """Убрать управляемое значение. Ключ становится ненастроенным."""
    if имя not in ВСЕ_КЛЮЧИ:
        raise ValueError(f"Настройка {имя} не используется Пультом")
    if задано_инфраструктурой(имя):
        raise ValueError(
            f"{имя} задан переменной окружения — убрать его можно только там, "
            "где он задан"
        )

    if имя in СВОЁ_ХРАНИЛИЩЕ:
        from app.services import telegram_settings

        строка = await telegram_settings.получить(session)
        if строка is not None:
            if имя == ТЕЛЕГРАМ_ТОКЕН:
                строка.bot_token = ""
                строка.bot_username = None
            else:
                строка.chat_id = ""
                строка.chat_title = None
    await session.execute(delete(AppSetting).where(AppSetting.key == имя))
    session.add(
        SettingsAudit(
            who=кто,
            integration=ИНТЕГРАЦИЯ_КЛЮЧА.get(имя, "?"),
            key=имя,
            action="removed",
        )
    )
    await session.commit()
    await загрузить(session)
    _забыть_ошибки({ИНТЕГРАЦИЯ_КЛЮЧА.get(имя, "")})
    _сбросить_кэш_клиентов()
    logger.info(f"настройка {имя} сброшена ({кто})")


def _забыть_ошибки(иды: set[str]) -> None:
    for ид in иды:
        _последняя_ошибка.pop(ид, None)


def _сбросить_кэш_клиентов() -> None:
    """Смена токена не должна ждать, пока истечёт кэш ответов YCLIENTS.

    Иначе после исправления отозванного токена человек ещё пять минут видит
    те же ошибки и решает, что настройка не применилась.
    """
    try:
        from app.services.cache import invalidate

        invalidate()
    except Exception as сбой:  # noqa: BLE001 — кэш необязателен для работы
        logger.debug(f"кэш не сброшен: {сбой}")


# ── Показ человеку ────────────────────────────────────────────────────────


def маска(значение_: str) -> str:
    """«••••••••7Kp2» — достаточно, чтобы узнать свой ключ, и мало, чтобы им воспользоваться."""
    if not значение_:
        return ""
    if len(значение_) <= 4:
        return "•" * 8
    return "•" * 8 + значение_[-4:]


def _поле(ключ: Ключ) -> dict[str, Any]:
    текущее = значение(ключ.имя)
    откуда = источник(ключ.имя)
    return {
        "key": ключ.имя,
        "title": ключ.заголовок,
        "hint": ключ.подсказка,
        "kind": "password" if ключ.секрет else ключ.вид,
        "secret": ключ.секрет,
        "required": ключ.обязательный,
        "configured": bool(текущее),
        # Секрет наружу не уходит никогда — ни целиком, ни в «скрытом» поле.
        # Несекретное показывается как есть: номер филиала полезно видеть.
        "display": маска(текущее) if ключ.секрет else текущее,
        "source": откуда,
        # Заданное инфраструктурой меняется только там, где задано.
        "locked": откуда == "process_env",
    }


def статус(ид: str) -> str:
    интеграция = ПО_ИД[ид]
    заполнено = [к for к in интеграция.обязательные if значение(к.имя)]
    if not заполнено:
        return ТРЕБУЕТСЯ
    if len(заполнено) < len(интеграция.обязательные):
        return ЧАСТИЧНО
    if ид in _последняя_ошибка:
        return ОШИБКА_СВЯЗИ
    return НАСТРОЕНО


def обзор() -> dict[str, Any]:
    """Всё, что нужно странице «Настройки → Интеграции». Без единого секрета."""
    список = []
    for интеграция in ИНТЕГРАЦИИ:
        список.append(
            {
                "id": интеграция.ид,
                "name": интеграция.название,
                "description": интеграция.описание,
                "critical": интеграция.критичная,
                "applies_immediately": интеграция.применяется_сразу,
                "status": статус(интеграция.ид),
                "error": _последняя_ошибка.get(интеграция.ид),
                "fields": [_поле(к) for к in интеграция.ключи],
            }
        )
    критичные_готовы = all(
        настроена(и.ид) for и in ИНТЕГРАЦИИ if и.критичная
    )
    return {
        "integrations": список,
        # Чего не хватает, чтобы Пульт показывал цифры.
        "ready": критичные_готовы,
        "missing": [
            к.имя
            for и in ИНТЕГРАЦИИ
            for к in и.обязательные
            if not значение(к.имя)
        ],
    }


# ── Разбор .env ───────────────────────────────────────────────────────────

ПРЕДЕЛ_ФАЙЛА = 256 * 1024  # 256 КБ: настоящий .env — единицы килобайт


def разобрать_env(текст: str) -> dict[str, str]:
    """KEY=value из текста файла. Файл не выполняется и в журнал не попадает.

    Понимает KEY=value, KEY="value", KEY='value'. Пустые строки и строки,
    начинающиеся с #, пропускаются. KEY=, KEY="" и KEY='' считаются
    отсутствующим значением — иначе загрузка файла с пустым TELEGRAM_CHAT_ID
    стирала бы настроенный чат.
    """
    разобрано: dict[str, str] = {}
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        if строка.startswith("export "):
            строка = строка[len("export ") :].strip()
        если_равно = строка.find("=")
        if если_равно <= 0:
            continue
        имя = строка[:если_равно].strip()
        значение_ = строка[если_равно + 1 :].strip()
        if not имя.replace("_", "").isalnum():
            continue
        if len(значение_) >= 2 and значение_[0] == значение_[-1] and значение_[0] in "\"'":
            значение_ = значение_[1:-1]
        if значение_:
            разобрано[имя.upper()] = значение_
    return разобрано


def предпросмотр(разобрано: dict[str, str]) -> dict[str, Any]:
    """Что будет, если применить этот файл. Сам файл при этом не применяется.

    Возвращает по каждой интеграции: что найдено, чего не хватает и каким
    станет её статус. Значения секретов — только масками.
    """
    известные = {и: з for и, з in разобрано.items() if и in ВСЕ_КЛЮЧИ}
    неизвестные = sorted(и for и in разобрано if и not in ВСЕ_КЛЮЧИ)

    список = []
    for интеграция in ИНТЕГРАЦИИ:
        поля = []
        станет_заполнено = 0
        for ключ in интеграция.ключи:
            в_файле = известные.get(ключ.имя, "")
            будет = в_файле or значение(ключ.имя)
            if ключ.обязательный and будет:
                станет_заполнено += 1
            поля.append(
                {
                    "key": ключ.имя,
                    "title": ключ.заголовок,
                    "found": bool(в_файле),
                    "required": ключ.обязательный,
                    "display": (маска(в_файле) if ключ.секрет else в_файле) if в_файле else "",
                    # Значение уже есть и файл его не трогает.
                    "kept": not в_файле and bool(значение(ключ.имя)),
                    "locked": задано_инфраструктурой(ключ.имя),
                }
            )
        всего = len(интеграция.обязательные)
        если_применить = (
            НАСТРОЕНО
            if станет_заполнено == всего
            else (ТРЕБУЕТСЯ if станет_заполнено == 0 else ЧАСТИЧНО)
        )
        список.append(
            {
                "id": интеграция.ид,
                "name": интеграция.название,
                "status_now": статус(интеграция.ид),
                "status_after": если_применить,
                "fields": поля,
            }
        )

    return {
        "integrations": список,
        "unknown": неизвестные,
        "applicable": sorted(известные),
    }


# ── Проверка подключения ──────────────────────────────────────────────────


async def проверить(ид: str) -> dict[str, Any]:
    """Сходить в сервис и убедиться, что ключи рабочие.

    Текст ошибки пишется для человека и никогда не содержит самих ключей:
    в ответах YCLIENTS и Telegram они встречаются, и пересказывать ответ
    целиком — значит показать токен в интерфейсе.
    """
    if ид not in ПО_ИД:
        raise ValueError(f"Неизвестная интеграция: {ид}")
    if not настроена(ид):
        _последняя_ошибка[ид] = "Заполнены не все обязательные поля"
        return {"ok": False, "message": _последняя_ошибка[ид], "status": статус(ид)}

    проверка = _ПРОВЕРКИ[ид]
    try:
        подробности = await проверка()
    except Exception as сбой:  # noqa: BLE001 — ответ показывается человеку
        текст = str(сбой).strip() or "Сервис не ответил"
        _последняя_ошибка[ид] = текст
        logger.warning(f"проверка {ид} не прошла: {текст}")
        return {"ok": False, "message": текст, "status": ОШИБКА_СВЯЗИ}

    _последняя_ошибка.pop(ид, None)
    return {"ok": True, "message": подробности, "status": статус(ид)}


async def _проверить_yclients() -> str:
    """Минимальный запрос: список сотрудников нужного филиала.

    Он подтверждает сразу три вещи — токен принят, авторизация работает,
    филиал доступен. Более лёгкого запроса, который проверяет всё это, у
    YCLIENTS нет.
    """
    from app.api.yclients import YClientsClient

    async with YClientsClient() as клиент:
        сотрудники = await клиент.get_staff()
    if not сотрудники:
        raise RuntimeError(
            "Ответ получен, но сотрудников в нём нет. Обычно это значит, что "
            "токен выдан на другой филиал или у него отозвали права."
        )
    return f"Филиал отвечает, сотрудников: {len(сотрудники)}"


async def _проверить_telegram() -> str:
    from app.services import telegram

    токен = значение("TELEGRAM_BOT_TOKEN")
    чат = значение("TELEGRAM_CHAT_ID")
    бот = await telegram.узнать_бота(токен)
    подробности = await telegram.проверить_чат(токен, чат)
    имя_чата = подробности.get("title") or чат
    return f"Бот @{бот.get('username') or '?'} видит чат «{имя_чата}»"


async def получить_пользовательский_токен(
    session: AsyncSession, логин: str, пароль: str, кто: str
) -> str:
    """Выменять логин и пароль кабинета YCLIENTS на пользовательский токен.

    Партнёрский токен виден в кабинете YCLIENTS, а пользовательский — нет: его
    выдают только в обмен на логин и пароль сотрудника. Раньше для этого был
    скрипт в терминале; владельцу без доступа к серверу он недоступен.

    Логин и пароль не сохраняются и не пишутся в журнал: они нужны на один
    запрос. Сохраняется только полученный токен — туда же, куда его вписали бы
    руками. Возвращает имя сотрудника, на которого выдан токен.
    """
    import httpx

    партнёрский = значение("YCLIENTS_PARTNER_TOKEN")
    if not партнёрский:
        raise ValueError("Сначала впишите партнёрский токен — без него YCLIENTS не ответит")
    if not логин.strip() or not пароль:
        raise ValueError("Нужны и логин, и пароль от кабинета YCLIENTS")

    try:
        async with httpx.AsyncClient(
            base_url="https://api.yclients.com/api/v1", timeout=30.0
        ) as клиент:
            ответ = await клиент.post(
                "/auth",
                json={"login": логин.strip(), "password": пароль},
                headers={
                    "Authorization": f"Bearer {партнёрский}",
                    "Accept": "application/vnd.yclients.v2+json",
                    "Content-Type": "application/json",
                },
            )
    except httpx.HTTPError as сбой:
        raise RuntimeError("YCLIENTS не ответил — проверьте интернет и попробуйте ещё раз") from сбой

    try:
        тело = ответ.json()
    except ValueError:
        тело = {}
    данные = (тело.get("data") or {}) if isinstance(тело, dict) else {}
    токен = данные.get("user_token")
    if not токен:
        # Ответ YCLIENTS целиком не пересказываем: в нём бывает эхо запроса.
        logger.warning(f"YCLIENTS не выдал токен, код {ответ.status_code}")
        raise ValueError(
            "YCLIENTS не принял логин или пароль. Это логин от кабинета YCLIENTS "
            "(телефон без плюса, например 79991234567, или почта), а не от Пульта."
        )

    await сохранить(session, {"YCLIENTS_USER_TOKEN": токен}, кто)
    return str(данные.get("name") or "сотрудник")


