def клиент_записи(запись: dict) -> int | None:
    """Стабильный client_id YCLIENTS или None, если записи не с клиентом.

    Имя клиента идентификатором быть не может (§26 ТЗ): тёзки склеятся в
    одного человека, а сменивший фамилию раздвоится.
    """
    клиент = запись.get("client") or {}
    ident = клиент.get("id")
    try:
        return int(ident) if ident else None
    except (TypeError, ValueError):
        return None


def клиентская(запись: dict) -> bool:
    """Запись клиента на услугу, а не техническое событие.

    Перерывы, личное время и блокировки расписания приезжают тем же адресом
    и без клиента либо без услуг. Считать их записями нельзя ни в плане
    денег, ни в количестве (§7, §15 ТЗ).
    """
    if запись.get("deleted"):
        return False
    if клиент_записи(запись) is None:
        return False
    return bool(запись.get("services"))


def актуальная(запись: dict) -> bool:
    """Запись, которая на момент расчёта ещё в силе.

    Не пришедший клиент из плана выпадает: его деньги уже не придут.
    """
    return клиентская(запись) and visit_attendance(запись) != НЕ_ПРИШЁЛ


def выполненная(запись: dict) -> bool:
    return клиентская(запись) and visit_attendance(запись) == ПРИШЁЛ


def в_день(запись: dict, день: date) -> bool:
    return timestamp(запись.get("datetime") or запись.get("date")).date() == день


