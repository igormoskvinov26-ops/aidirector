"""Открытие и закрытие смены: расчёты по данным YCLIENTS.

Модуль по ТЗ владельца от 23.09.2026. Два разных сценария одного дня:

* **открытие** — снимок плана на утро. Что записано, сколько это денег, кто
  из мастеров работает, и кто из записанных придёт впервые, во второй раз
  или за пятым визитом;
* **закрытие** — факт вечера. Пересчитывается заново по свежим данным, а не
  берётся утренний снимок: за день записи отменяют, добавляют и не приходят.

Своей выгрузки из YCLIENTS здесь нет. Записи берутся тем же вызовом, что и
«Записи за месяц» (barber_month.pages), деньги считает тот же amount(),
признак посещения — тот же visit_attendance(), товары — тот же
load_products(). Второй интеграции в проекте быть не должно.

Показатели, которые считаются по всей жизни клиента (новый, второй визит,
станут постоянными, стали потерянными), требуют числа выполненных визитов
до сегодняшнего дня. Наша база визитов хранит только окно синхронизации —
90 дней, поэтому считать по ней нельзя: у клиента, приходящего раз в
полгода, там будет не то число. Пока источник такого счётчика не подтверждён
на живом API, эти показатели отдаются как «данные недоступны» (§33 ТЗ:
подменять ошибку получения данных нулём запрещено).
"""

from datetime import date, datetime, timedelta
from decimal import Decimal

from loguru import logger

from app.api.yclients import YClientsClient
from app.config import settings
from app.services.barber_month import (
    MOSCOW,
    amount,
    load_products,
    money,
    pages,
    timestamp,
    visit_attendance,
)

# Насколько вперёд ищем следующую запись клиента. Дальше барбершоп не пишет:
# окно выгрузки проекта — 60 дней вперёд, берём с запасом.
БУДУЩЕЕ_ОКНО_ДНЕЙ = 90

# Порог постоянного клиента — пятый выполненный визит (§10 ТЗ, решение
# владельца 23.09.2026). То же число стоит в «Пульсе базы».
ПОРОГ_ПОСТОЯННОГО = 5

# Признак посещения: −1 «не пришёл», 0 «ожидание», 1 «пришёл», 2 «подтвердил».
НЕ_ПРИШЁЛ = -1
ПРИШЁЛ = 1
ОЖИДАНИЕ = (0, 2)

НЕТ_ДАННЫХ = None

МЕСЯЦЫ = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)


def moscow_now() -> datetime:
    return datetime.now(MOSCOW)


def moscow_today() -> date:
    return moscow_now().date()


def по_русски(день: date) -> str:
    return f"{день.day} {МЕСЯЦЫ[день.month - 1]}"


def рубли(сумма: Decimal | float | None) -> str:
    """«78 500 ₽» — с пробелом между тысячами, без копеек."""
    if сумма is None:
        return "данные недоступны"
    return f"{int(round(float(сумма))):,}".replace(",", " ") + " ₽"


def число(значение: int | None) -> str:
    return "данные недоступны" if значение is None else str(значение)


