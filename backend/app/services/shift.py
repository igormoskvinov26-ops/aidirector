def _имена_барберов() -> dict[int, str]:
    return {int(r["staff_id"]): r["name"] for r in settings.barber_payroll_rules}


def _строка_услуги(запись: dict, имена: dict[int, str]) -> dict:
    """Одна строка расшифровки: за что заплатили, кто вёл, во сколько."""
    услуги = запись.get("services") or []
    названия = ", ".join(str(s.get("title") or "Услуга") for s in услуги) or "Услуга"
    staff_id = int(запись.get("staff_id") or (запись.get("staff") or {}).get("id") or 0)
    return {
        "client_id": клиент_записи(запись),
        "master": имена.get(staff_id, "—"),
        "title": названия,
        "amount": float(amount(запись)),
        "time": timestamp(запись.get("datetime") or запись.get("date")).strftime("%H:%M"),
    }


async def собрать_детали_услуг(день: date | None = None) -> list[dict]:
    """Расшифровка сегодняшней выручки по услугам — по одной строке на визит.

    Клиент отдаётся только как client_id: показывать его имя — дело слоя,
    у которого есть доступ к локальной базе (shift_store), а не этого модуля,
    который сознательно ходит только в YCLIENTS.
    """
    день = день or moscow_today()
    имена = _имена_барберов()
    async with YClientsClient() as client:
        записи = await загрузить_день(client, день)
    выполненные = [з for з in записи if клиентская(з) and в_день(з, день) and выполненная(з)]
    строки = [_строка_услуги(з, имена) for з in выполненные]
    строки.sort(key=lambda с: с["time"])
    return строки


async def собрать_детали_товаров(день: date | None = None) -> list[dict]:
    """Расшифровка сегодняшней выручки по товарам — по одной строке на продажу."""
    день = день or moscow_today()
    имена = _имена_барберов()
    async with YClientsClient() as client:
        продажи = await load_products(client, день.isoformat(), день.isoformat())
    return [
        {
            "master": имена.get(int(p.get("staff_id") or 0), "—"),
            "title": p.get("title") or "Товар",
            "amount": float(money(p["amount"])),
        }
        for p in продажи
    ]


async def собрать_закрытие(день: date | None = None) -> dict:
    """Факт за день. Данные запрашиваются заново — утренний снимок не годится."""
    день = день or moscow_today()
    предупреждения: list[str] = []

    async with YClientsClient() as client:
        # Одной выгрузкой за 60 дней вместо двух: в ней лежат и сегодняшние
        # записи, и то, что нужно для «стали потерянными сегодня».
        окно = await загрузить_окно_потерь(client, день)
        записи = [з for з in окно if в_день(з, день)]
        будущие = await загрузить_будущее(client, день)
        мастера, предупреждение = await работающие_мастера(client, день, записи)
        if предупреждение:
            предупреждения.append(предупреждение)
        try:
            продажи = await load_products(client, день.isoformat(), день.isoformat())
            товары = float(sum((money(p["amount"]) for p in продажи), Decimal(0)))
        except Exception as сбой:  # noqa: BLE001
            logger.warning(f"смена {день}: продажи товаров недоступны: {сбой}")
            товары = НЕТ_ДАННЫХ
            предупреждения.append("Продажи товаров недоступны: выручка по товарам не рассчитана.")

        записались, не_записались, пришли = записался_дальше(записи, будущие, день)
        визитов = await визитов_до_сегодня(client, пришли, день)

    дневные = [з for з in записи if клиентская(з) and в_день(з, день)]
    выполнены = [з for з in дневные if выполненная(з)]
    услуги = float(sum((amount(з) for з in выполнены), Decimal(0)))

    if визитов is None:
        предупреждения.append(
            "История визитов клиентов недоступна: новые и ставшие постоянными не рассчитаны."
        )
    предупреждения.append(
        "«Создано сегодня на будущие даты» не рассчитано: в записи YCLIENTS нет "
        "подтверждённого поля с датой создания."
    )
    предупреждения.append(
        "Деньги: разбивка по безналу/наличке и «потрачено» не рассчитаны — "
        "источник данных в YCLIENTS не подтверждён."
    )

    итог = {
        "shift_date": день.isoformat(),
        "records_total": len(дневные),
        "records_completed": len(выполнены),
        "services_revenue": услуги,
        "products_revenue": товары,
        # Деньги (запрос владельца 26.09.2026). Заработано всего считается
        # уверенно — те же услуги и товары, что и строками выше. Остальное
        # требует полей, которых мы пока не подтвердили на живом API
        # (§39 ТЗ смены: не угадывать имена полей) — «данные недоступны»,
        # а не ноль, который выглядел бы как «расхода не было».
        "money": {
            "total_earned": None if товары is None else услуги + товары,
            "non_cash": НЕТ_ДАННЫХ,
            "cash": НЕТ_ДАННЫХ,
            "spent": НЕТ_ДАННЫХ,
            # Остатки и долг подставляются слоем с доступом к базе
            # (shift_store.закрыть, через cash_balances) — здесь только
            # заготовка формы, чтобы ключ существовал даже без базы под рукой.
            "cash_register_estimate": НЕТ_ДАННЫХ,
            "settlement_account_estimate": НЕТ_ДАННЫХ,
            "other_account_debt": НЕТ_ДАННЫХ,
        },
        "clients_came": len(пришли),
        "clients": {"booked_next": записались, "not_booked": не_записались},
        # Создано сегодня на будущие даты (§21 ТЗ): у записи YCLIENTS не
        # подтверждено поле с датой создания, а угадывать его запрещено (§39).
        "created_today_for_future": НЕТ_ДАННЫХ,
        "completed": разложить_пришедших(пришли, визитов),
        "lost_today": стали_потерянными(окно, будущие, день),
        "masters": мастера,
        "warnings": предупреждения,
        "calculated_at": moscow_now().isoformat(),
    }

    сбои = проверки(итог)
    if сбои:
        # Не прятать: по этой строке видно, что цифрам верить нельзя.
        logger.error(f"смена {день}: проверки целостности не прошли: {'; '.join(сбои)}")
    итог["integrity_failures"] = сбои
    return итог


