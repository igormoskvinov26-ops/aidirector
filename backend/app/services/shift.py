async def визитов_до_сегодня(
    client: YClientsClient, client_ids: set[int], день: date
) -> dict[int, int] | None:
    """Сколько выполненных визитов было у клиента ДО этого дня.

    Возвращает None, пока источник не подтверждён на живом API. Ни база
    проекта (окно 90 дней), ни угаданное имя поля справочника клиентов для
    этого не годятся: «новый», «второй визит» и «станет постоянным» считаются
    по всей жизни клиента, и ошибка здесь тихо испортит все четыре показателя
    сразу.

    Пока None — показатели выводятся как «данные недоступны» (§33 ТЗ), а не
    нулями. Проверка источника: scripts/показать-поля-записи.py.
    """
    return НЕТ_ДАННЫХ


