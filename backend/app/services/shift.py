async def визитов_до_сегодня(
    client: YClientsClient, client_ids: set[int], день: date
) -> dict[int, int] | None:
    """Сколько выполненных визитов было у клиента ДО этого дня.

    История спрашивается поимённо: /records/ с условием client_id. Что
    условие действительно отбирает записи одного клиента, а не отбрасывается
    молча, проверено на живом API 23.09.2026 — scripts/показать-поля-записи.py.
    Ответ дополнительно отфильтрован по client_id ещё раз: если YCLIENTS
    когда-нибудь перестанет понимать это условие, показатель обнулится
    заметно, а не подрастёт чужими визитами.

    Считаются только выполненные визиты строго до указанного дня. Сегодняшний
    визит в счёт не идёт: он и есть тот, чей номер мы определяем (§11 ТЗ).

    Базой проекта считать нельзя: она хранит визиты за окно синхронизации в
    90 дней, и у клиента, приходящего раз в полгода, там будет не то число.

    Возвращает None, если хоть один запрос не прошёл: недосчитанная история
    даёт правдоподобные и неверные цифры, а «данные недоступны» — честные.
    """
    if not client_ids:
        return {}

    итог: dict[int, int] = {}
    try:
        for cid in sorted(client_ids):
            итог[cid] = await _история_одного(client, cid, день)
            await asyncio.sleep(ПАУЗА_МЕЖДУ_ЗАПРОСАМИ)
    except Exception as сбой:  # noqa: BLE001 — показать «нет данных», а не половину
        logger.error(f"смена {день}: история визитов недоступна: {сбой}")
        return НЕТ_ДАННЫХ
    return итог


async def _история_одного(client: YClientsClient, cid: int, день: date) -> int:
    """Выполненные визиты одного клиента до указанного дня.

    Свой цикл страниц, а не общий pages() из «Записей за месяц»: там окно —
    месяц, а здесь одиннадцать лет, и если YCLIENTS перестанет понимать
    условие client_id, общий цикл добросовестно выкачает всю историю салона
    страницами по двести. Поэтому здесь два своих правила: предел страниц
    жёсткий, и чужая запись в ответе — сразу ошибка, а не повод считать
    дальше. Показать «данные недоступны» честнее, чем показать чужие визиты.
    """
    параметры = {
        "start_date": ИСТОРИЯ_С.isoformat(),
        "end_date": (день - timedelta(days=1)).isoformat(),
        "client_id": cid,
        "count": 200,
    }
    визитов, ранее = 0, set()
    for страница in range(1, СТРАНИЦ_ИСТОРИИ + 1):
        ответ = await client._get(f"/records/{client.company_id}", {**параметры, "page": страница})
        строки = ответ.get("data") if isinstance(ответ, dict) else ответ
        if not isinstance(строки, list):
            raise ValueError("YCLIENTS вернул историю клиента не списком")
        if not строки:
            return визитов
        if any(клиент_записи(з) not in (None, cid) for з in строки):
            raise ValueError(f"условие client_id={cid} не отобрало записи: в ответе чужие")
        свежие = [з for з in строки if з.get("id") not in ранее]
        if not свежие:
            raise ValueError("YCLIENTS повторяет страницу истории клиента")
        ранее.update(з.get("id") for з in свежие)
        визитов += sum(1 for з in свежие if выполненная(з))
        всего = (ответ.get("meta") or {}).get("total_count") if isinstance(ответ, dict) else None
        if всего is not None and len(ранее) >= int(всего):
            return визитов
        await asyncio.sleep(ПАУЗА_МЕЖДУ_ЗАПРОСАМИ)
    raise ValueError(f"история клиента {cid} не поместилась в {СТРАНИЦ_ИСТОРИИ} страниц")


