def разложить_записанных(
    записи: list[dict], день: date, визитов: dict[int, int] | None
) -> dict[str, int | None]:
    """Новые, второй визит и «станут постоянными» среди записанных на день.

    Считаются люди, а не услуги (§17 ТЗ): клиент с двумя записями в один день
    учитывается один раз. Классификация — по числу выполненных визитов ДО
    сегодняшнего: 0 → новый, 1 → второй визит, 4 → станет постоянным,
    5 и больше → уже постоянный, ни в один показатель не входит.
    """
    if визитов is None:
        return {"new": НЕТ_ДАННЫХ, "second": НЕТ_ДАННЫХ, "will_be_regular": НЕТ_ДАННЫХ}

    люди = {
        клиент_записи(з)
        for з in записи
        if актуальная(з) and в_день(з, день) and клиент_записи(з) is not None
    }
    было = {cid: визитов.get(cid, 0) for cid in люди}
    return {
        "new": sum(1 for n in было.values() if n == 0),
        "second": sum(1 for n in было.values() if n == 1),
        "will_be_regular": sum(1 for n in было.values() if n == ПОРОГ_ПОСТОЯННОГО - 1),
    }


def план_дня(записи: list[dict], день: date) -> Decimal:
    """Сумма услуг по всем актуальным записям дня. Товары сюда не входят."""
    итог = Decimal(0)
    for з in записи:
        if актуальная(з) and в_день(з, день):
            итог += amount(з)
    return итог


async def собрать_открытие(день: date | None = None) -> dict:
    """Снимок на начало дня. Сохраняется как есть — отмены после не меняют его."""
    день = день or moscow_today()
    async with YClientsClient() as client:
        записи = await загрузить_день(client, день)
        мастера, предупреждение = await работающие_мастера(client, день, записи)
        люди = {
            cid
            for з in записи
            if актуальная(з) and в_день(з, день) and (cid := клиент_записи(з)) is not None
        }
        визитов = await визитов_до_сегодня(client, люди, день)

    клиенты = разложить_записанных(записи, день, визитов)
    предупреждения = [предупреждение] if предупреждение else []
    if визитов is None:
        предупреждения.append(
            "История визитов клиентов недоступна: новые, второй визит и «станут "
            "постоянными» не рассчитаны."
        )

    return {
        "shift_date": день.isoformat(),
        "plan": float(план_дня(записи, день)),
        "masters_working": len(мастера),
        "masters": мастера,
        "clients": клиенты,
        "warnings": предупреждения,
        "calculated_at": moscow_now().isoformat(),
    }


