async def загрузить_день(client: YClientsClient, день: date) -> list[dict]:
    """Все записи одного дня. Тот же путь, которым ходят «Записи за месяц»."""
    iso = день.isoformat()
    return await pages(client, f"/records/{client.company_id}", iso, iso)


async def загрузить_будущее(client: YClientsClient, день: date) -> list[dict]:
    """Записи на дни после указанного — чтобы видеть, кто ушёл с записью."""
    начало = (день + timedelta(days=1)).isoformat()
    конец = (день + timedelta(days=БУДУЩЕЕ_ОКНО_ДНЕЙ)).isoformat()
    return await pages(client, f"/records/{client.company_id}", начало, конец)


async def работающие_мастера(
    client: YClientsClient, день: date, записи: list[dict]
) -> tuple[list[dict], str | None]:
    """Барберы, работающие в этот день, и предупреждение, если график не дали.

    В счёт идут только барберы из настроек оплаты — управляющий и
    администратор мастерами не считаются (§5 ТЗ). Имена в расчётной логике
    не участвуют: сверка идёт по staff_id.

    График — основной источник: мастер работает и тогда, когда к нему ещё
    никто не записан. Запись в этот день — второй источник: выполненный или
    ожидаемый визит доказывает смену, даже если график потом переписали.
    """
    барберы = [
        {"staff_id": int(r["staff_id"]), "name": str(r["name"])}
        for r in settings.barber_payroll_rules
    ]
    по_записям = {
        int(з.get("staff_id") or (з.get("staff") or {}).get("id") or 0)
        for з in записи
        if актуальная(з)
    }

    предупреждение = None
    по_графику: set[int] = set()
    try:
        сырое = await client._get(
            f"/company/{client.company_id}/staff/schedule",
            {"start_date": день.isoformat(), "end_date": день.isoformat()},
        )
        строки = сырое.get("data")
        if not isinstance(строки, list):
            raise ValueError("график YCLIENTS вернул не список")
        for строка in строки:
            ident = int(строка.get("staff_id") or строка.get("staffId") or 0)
            if ident and строка.get("slots"):
                по_графику.add(ident)
    except Exception as сбой:  # noqa: BLE001 — недоступный график не должен ронять смену
        logger.warning(f"смена {день}: график YCLIENTS недоступен: {сбой}")
        предупреждение = (
            "График YCLIENTS недоступен: работающими считаются только мастера, "
            "у которых на сегодня есть записи."
        )

    работают = [м for м in барберы if м["staff_id"] in по_графику | по_записям]
    return работают, предупреждение


