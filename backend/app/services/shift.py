def записался_дальше(
    записи_дня: list[dict], будущие: list[dict], день: date
) -> tuple[int, int, set[int]]:
    """Кто из пришедших сегодня ушёл со следующей записью, а кто нет.

    Смотрим только на тех, кто сегодня фактически был (§19 ТЗ). Не важно,
    когда будущая запись создана: важно, есть ли она у человека на руках.
    """
    пришли: dict[int, datetime] = {}
    for з in записи_дня:
        cid = клиент_записи(з)
        if cid is None or not выполненная(з) or not в_день(з, день):
            continue
        когда = timestamp(з.get("datetime") or з.get("date"))
        пришли[cid] = max(когда, пришли[cid]) if cid in пришли else когда

    с_записью: set[int] = set()
    for з in [*записи_дня, *будущие]:
        cid = клиент_записи(з)
        if cid not in пришли or not клиентская(з):
            continue
        if visit_attendance(з) not in ОЖИДАНИЕ:
            continue
        if timestamp(з.get("datetime") or з.get("date")) > пришли[cid]:
            с_записью.add(cid)

    return len(с_записью), len(пришли) - len(с_записью), set(пришли)


def разложить_пришедших(
    пришли: set[int], визитов: dict[int, int] | None
) -> dict[str, int | None]:
    """Новые и ставшие постоянными — только по фактически выполненным визитам."""
    if визитов is None:
        return {"new": НЕТ_ДАННЫХ, "became_regular": НЕТ_ДАННЫХ}
    было = {cid: визитов.get(cid, 0) for cid in пришли}
    return {
        "new": sum(1 for n in было.values() if n == 0),
        "became_regular": sum(1 for n in было.values() if n == ПОРОГ_ПОСТОЯННОГО - 1),
    }


def проверки(итог: dict) -> list[str]:
    """Проверки целостности §34 ТЗ. Нарушение — ошибка расчёта, не мелочь."""
    сбои = []
    if итог["records_completed"] > итог["records_total"]:
        сбои.append("выполнено больше, чем записано")
    клиенты = итог["clients"]
    пришло = итог["clients_came"]
    if клиенты["booked_next"] + клиенты["not_booked"] != пришло:
        сбои.append("записались плюс не записались не равно числу пришедших клиентов")
    for ключ in ("new", "became_regular"):
        if итог["completed"][ключ] is not None and итог["completed"][ключ] > пришло:
            сбои.append(f"{ключ}: больше, чем пришло клиентов")
    if итог["services_revenue"] < 0:
        сбои.append("выручка по услугам отрицательная")
    if итог["products_revenue"] is not None and итог["products_revenue"] < 0:
        сбои.append("выручка по товарам отрицательная")
    return сбои


async def собрать_закрытие(день: date | None = None) -> dict:
    """Факт за день. Данные запрашиваются заново — утренний снимок не годится."""
    день = день or moscow_today()
    предупреждения: list[str] = []

    async with YClientsClient() as client:
        записи = await загрузить_день(client, день)
        будущие = await загрузить_будущее(client, день)
        мастера, предупреждение = await работающие_мастера(client, день, записи)
        if предупреждение:
            предупреждения.append(предупреждение)
        try:
            продажи = await load_products(client, день.isoformat(), день.isoformat())
            товары = float(sum((money(p["amount"]) for p in продажи), Decimal(0)))
        except Exception as сбой:  # noqa: BLE001
            logger.warning(f"смена {день}: продажи товаров недоступны: {сбой}")
            товары = НЕТ_ДАННЫХ
            предупреждения.append("Продажи товаров недоступны: выручка по товарам не рассчитана.")

        записались, не_записались, пришли = записался_дальше(записи, будущие, день)
        визитов = await визитов_до_сегодня(client, пришли, день)

    дневные = [з for з in записи if клиентская(з) and в_день(з, день)]
    выполнены = [з for з in дневные if выполненная(з)]
    услуги = float(sum((amount(з) for з in выполнены), Decimal(0)))

    if визитов is None:
        предупреждения.append(
            "История визитов клиентов недоступна: новые и ставшие постоянными не рассчитаны."
        )
    предупреждения.append(
        "Создано сегодня на будущие даты и стали потерянными: источник данных не подтверждён."
    )

    итог = {
        "shift_date": день.isoformat(),
        "records_total": len(дневные),
        "records_completed": len(выполнены),
        "services_revenue": услуги,
        "products_revenue": товары,
        "clients_came": len(пришли),
        "clients": {"booked_next": записались, "not_booked": не_записались},
        # Создано сегодня на будущие даты (§21 ТЗ): у записи YCLIENTS не
        # подтверждено поле с датой создания, а угадывать его запрещено (§39).
        "created_today_for_future": НЕТ_ДАННЫХ,
        "completed": разложить_пришедших(пришли, визитов),
        # Стали потерянными сегодня (§25 ТЗ) считаются по дате последнего
        # выполненного визита за всю историю — тот же недостающий источник.
        "lost_today": НЕТ_ДАННЫХ,
        "masters": мастера,
        "warnings": предупреждения,
        "calculated_at": moscow_now().isoformat(),
    }

    сбои = проверки(итог)
    if сбои:
        # Не прятать: по этой строке видно, что цифрам верить нельзя.
        logger.error(f"смена {день}: проверки целостности не прошли: {'; '.join(сбои)}")
    итог["integrity_failures"] = сбои
    return итог


