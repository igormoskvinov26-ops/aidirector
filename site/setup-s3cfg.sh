#!/usr/bin/env bash
# ==========================================================================
#  Создаёт ~/.s3cfg с ключами сервисного аккаунта Yandex Cloud.
#
#  Запускается без аргументов — ключи скрипт спросит сам:
#
#      ./setup-s3cfg.sh
#
#  Спрашивает он их, а не вы подставляете заранее, по двум причинам: ключи
#  не попадают в историю команд, и не нужно знать, как читает ввод именно
#  ваша оболочка (у bash и zsh это разные флаги, и на них легко споткнуться).
#
#  Для автоматической установки ключи можно передать через окружение:
#  YC_KEY_ID и YC_SECRET. Тогда вопросов не будет.
#
#  Где взять ключи: консоль → Сервисные аккаунты → нужный аккаунт →
#  Создать новый ключ → Создать статический ключ доступа.
#
#  Про host_bucket: намеренно указан тот же адрес, что и host_base, —
#  это адресация вида storage.yandexcloud.net/имя-бакета/файл.
#  Обычный для S3 вариант имя-бакета.storage.yandexcloud.net здесь не
#  работает: в имени нашего бакета есть точка, и такое имя не покрывается
#  сертификатом *.storage.yandexcloud.net — соединение рвётся на проверке
#  сертификата. Не «упрощайте» эту строку обратно.
# ==========================================================================
set -euo pipefail

# Скрипт исполняется bash-ом (см. строку выше), поэтому read -s -p здесь
# работает независимо от того, из какой оболочки его запустили.
if [ -z "${YC_KEY_ID:-}" ]; then
    printf 'Ключи сервисного аккаунта Yandex Cloud.\n'
    printf 'Вводятся вслепую — на экране ничего не появится, это нормально.\n\n'
    read -r -s -p "Идентификатор ключа (YCAJE...): " YC_KEY_ID || true; echo
fi
if [ -z "${YC_SECRET:-}" ]; then
    read -r -s -p "Секретный ключ: " YC_SECRET || true; echo
fi

# Обрезаем пробелы и переводы строк по краям: при копировании из консоли
# они цепляются незаметно, а подпись запроса от них разъезжается, и Yandex
# отвечает невнятным SignatureDoesNotMatch.
YC_KEY_ID="$(printf '%s' "$YC_KEY_ID" | tr -d '[:space:]')"
YC_SECRET="$(printf '%s' "$YC_SECRET" | tr -d '[:space:]')"

[ -n "$YC_KEY_ID" ] || { echo "Идентификатор ключа не введён."; exit 1; }
[ -n "$YC_SECRET" ] || { echo "Секретный ключ не введён."; exit 1; }

# Ключи легко перепутать местами: оба вводятся вслепую, а идентификатор
# узнаётся по началу YCAJE. Лучше сказать сразу, чем гадать по 403.
case "$YC_SECRET" in
    YCAJE*) echo "Похоже, значения перепутаны: секрет начинается на YCAJE —"
            echo "так начинается идентификатор ключа, а не секрет."
            echo "Запустите скрипт заново и поменяйте их местами."
            exit 1 ;;
esac
case "$YC_KEY_ID" in
    YCAJE*) : ;;
    *) echo "Внимание: идентификатор ключа обычно начинается на YCAJE."
       echo "Если подпись не сойдётся — проверьте, что вставлено." ;;
esac

echo

umask 077
cat > ~/.s3cfg <<CFG
[default]
access_key = $YC_KEY_ID
secret_key = $YC_SECRET
host_base = storage.yandexcloud.net
host_bucket = storage.yandexcloud.net
bucket_location = ru-central1
use_https = True
signature_v2 = False
CFG
chmod 600 ~/.s3cfg

echo "✓ ~/.s3cfg записан, права 600"
echo "  Проверка доступа:"
s3cmd ls 2>&1 | sed 's/^/    /'
