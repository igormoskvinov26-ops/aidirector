"""Получить пользовательский токен YCLIENTS и вписать его в .env.

Пользовательский токен в настройках YCLIENTS не показывают: его выдают в
обмен на логин и пароль сотрудника. Этот скрипт спрашивает их, получает
токен, проверяет его и сам правит .env — прежний файл сохраняется рядом.

Работает на стандартной библиотеке: ни httpx, ни uv, ни контейнера не нужно.
Причина не в аккуратности, а в том, что .env лежит на компьютере, а не
внутри контейнера, — править его надо оттуда, где он есть.

Запуск:
    python3 scripts/обновить-токен.py
    python3 scripts/обновить-токен.py ~/rubl-director/.env

Пароль спрашивается при запуске, на экране не виден, никуда не пишется.
Сам токен на экран не печатается: он такой же секрет, как пароль.
"""

import getpass
import json
import os
import sys
import urllib.error
import urllib.request
from datetime import datetime
from pathlib import Path

BASE_URL = "https://api.yclients.com/api/v1"
ЗАГОЛОВОК = "Accept"
ТИП = "application/vnd.yclients.v2+json"


# --------------------------------------------------------------------------- #
# Файл настроек
# --------------------------------------------------------------------------- #


def найти_env(аргумент: str | None) -> Path:
    """Где лежит .env. Явный путь важнее догадок."""
    if аргумент:
        путь = Path(аргумент).expanduser()
        if not путь.is_file():
            завершить(f"Файла {путь} нет.")
        return путь

    кандидаты = [
        Path(__file__).resolve().parent.parent / ".env",
        Path.cwd() / ".env",
        Path.home() / "rubl-director" / ".env",
    ]
    for путь in кандидаты:
        if путь.is_file():
            return путь
    завершить(
        "Файл .env не найден. Укажите путь явно:\n"
        "    python3 scripts/обновить-токен.py ~/rubl-director/.env"
    )
    raise AssertionError  # до сюда не доходит, нужно для типов


def прочитать(путь: Path, ключ: str) -> str:
    """Значение одной строки .env. Разбираем сами, без сторонних библиотек.

    Комментарий после пробела отбрасывается — так же, как это делает сам
    загрузчик настроек приложения. Иначе значение здесь и значение там
    разошлись бы, и скрипт проверял бы не тот токен, который пойдёт в дело.
    """
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка.startswith(f"{ключ}="):
            continue
        значение = строка.partition("=")[2]
        решётка = значение.find(" #")
        if решётка != -1:
            значение = значение[:решётка]
        return значение.strip().strip('"').strip("'")
    return ""


def подменить_строку(текст: str, ключ: str, значение: str) -> str:
    """Заменить значение ключа, не тронув ничего вокруг.

    Комментарии, порядок строк и переводы строк сохраняются: файл человек
    читает глазами, и перетасовывать его из-за одной правки нельзя.
    """
    строки = текст.splitlines(keepends=True)
    перевод = "\n"
    заменено = False

    for номер, строка in enumerate(строки):
        if строка.strip().startswith(f"{ключ}="):
            хвост = строка[len(строка.rstrip("\r\n")):] or перевод
            строки[номер] = f"{ключ}={значение}{хвост}"
            заменено = True
            break

    if not заменено:
        # Строки нет вовсе — дописываем в конец, отделив от предыдущей.
        если_нужен_перевод = "" if not текст or текст.endswith("\n") else перевод
        строки.append(f"{если_нужен_перевод}{ключ}={значение}{перевод}")

    return "".join(строки)


def сохранить(путь: Path, текст: str) -> Path:
    """Записать .env, отложив прежний в сторону.

    Копия делается всегда: файл содержит пароли, которые владелец придумывал
    руками, и восстановить их из ниоткуда нельзя.
    """
    копия = путь.with_name(f"{путь.name}.до-{datetime.now():%Y%m%d-%H%M%S}")
    копия.write_bytes(путь.read_bytes())
    os.chmod(копия, 0o600)
    путь.write_text(текст, encoding="utf-8")
    os.chmod(путь, 0o600)
    return копия


# --------------------------------------------------------------------------- #
# YCLIENTS
# --------------------------------------------------------------------------- #


def запрос(путь: str, партнёр: str, пользователь: str = "", тело: dict | None = None):
    """Один запрос к YCLIENTS. Возвращает (код, разобранный ответ)."""
    ключ = f"Bearer {партнёр}"
    if пользователь:
        ключ += f", User {пользователь}"

    данные = json.dumps(тело).encode() if тело is not None else None
    заявка = urllib.request.Request(
        f"{BASE_URL}{путь}",
        data=данные,
        headers={
            "Authorization": ключ,
            ЗАГОЛОВОК: ТИП,
            "Content-Type": "application/json",
        },
        method="POST" if тело is not None else "GET",
    )
    try:
        with urllib.request.urlopen(заявка, timeout=30) as ответ:
            return ответ.status, json.loads(ответ.read().decode())
    except urllib.error.HTTPError as ошибка:
        # Тело ошибки важнее кода: YCLIENTS объясняет отказ словами.
        сырое = ошибка.read().decode(errors="replace")
        try:
            return ошибка.code, json.loads(сырое)
        except ValueError:
            return ошибка.code, {"meta": {"message": сырое[:300]}}
    except urllib.error.URLError as ошибка:
        завершить(f"Нет связи с api.yclients.com: {ошибка.reason}")
        raise AssertionError


def сообщение(ответ: dict) -> str:
    мета = ответ.get("meta")
    if isinstance(мета, dict):
        return str(мета.get("message") or "")
    return ""


# --------------------------------------------------------------------------- #
# Ход дела
# --------------------------------------------------------------------------- #


def завершить(текст: str, код: int = 1) -> None:
    print(f"\n{текст}")
    sys.exit(код)


def main() -> None:
    путь = найти_env(sys.argv[1] if len(sys.argv) > 1 else None)
    партнёр = прочитать(путь, "YCLIENTS_PARTNER_TOKEN")
    филиал = прочитать(путь, "YCLIENTS_COMPANY_ID")

    print(f"Файл настроек: {путь}")
    if not партнёр or партнёр.startswith("<"):
        завершить(
            "В .env не заполнен YCLIENTS_PARTNER_TOKEN.\n"
            "Он есть в настройках YCLIENTS, в разделе для партнёров."
        )
    print(f"Партнёрский токен: {len(партнёр)} символов — на месте")
    print(f"Филиал в настройках: {филиал or 'не указан'}\n")

    print("Вход в YCLIENTS — те же логин и пароль, что на сайте yclients.com.")
    print("Это НЕ логин от Директора: тот мы придумали сами, YCLIENTS его не знает.")
    print("Телефон — без плюса и разделителей: 79991234567.")
    print("Пароль при вводе не отображается, это нормально.\n")

    try:
        логин = input("Логин (телефон или почта): ").strip()
        пароль = getpass.getpass("Пароль: ") if логин else ""
    except EOFError:
        завершить("Ввод закончился. Запускайте скрипт вручную в терминале.")
        return

    if not логин or not пароль:
        завершить("Логин и пароль нужны оба.")

    код, ответ = запрос("/auth", партнёр, тело={"login": логин, "password": пароль})
    токен = ((ответ.get("data") or {}) if isinstance(ответ.get("data"), dict) else {}).get(
        "user_token"
    )

    if not токен:
        print(f"\nТокен не выдан. YCLIENTS ответил (код {код}): {сообщение(ответ) or ответ}")
        завершить(
            "Что проверить:\n"
            "  1. Это логин от сайта yclients.com, а не от Директора.\n"
            "  2. Телефон без плюса и разделителей: 79991234567.\n"
            "     Не вышло — попробуйте почту, на которую заведён аккаунт.\n"
            "  3. Пароль набирается вслепую: раскладка и Caps Lock не видны."
        )

    имя = (ответ.get("data") or {}).get("name") or "сотрудник"
    print(f"\nТокен получен. Выдан для: {имя}")

    # Проверяем до записи: токен без доступа к филиалу так же бесполезен, как
    # прежний, и подменять одно на другое молча — значит спрятать причину.
    код_ф, филиалы = запрос("/companies?my=1", партнёр, токен)
    доступные = филиалы.get("data") or []
    номера = [str(ф.get("id")) for ф in доступные if isinstance(ф, dict)]

    if not номера:
        завершить(
            "Но доступа к филиалам у него нет: список пуст.\n"
            "Значит учётная запись, под которой вы вошли, не привязана к салону\n"
            "в YCLIENTS. Токен в .env не записан — записывать нечего.\n"
            "Войдите под той учётной записью, у которой есть доступ к филиалу."
        )

    print(f"Филиалов доступно: {len(номера)} — {', '.join(номера)}")
    попадает = филиал in номера

    текст = подменить_строку(
        путь.read_text(encoding="utf-8"), "YCLIENTS_USER_TOKEN", токен
    )
    копия = сохранить(путь, текст)
    print(f"\nТокен записан в {путь.name}. Прежний файл сохранён как {копия.name}.")

    if not попадает:
        завершить(
            f"Но филиала {филиал} среди доступных нет.\n"
            f"Либо в YCLIENTS_COMPANY_ID стоит не тот номер, либо у этой\n"
            f"учётной записи нет доступа именно к нему. Доступные: {', '.join(номера)}",
            код=2,
        )

    код_с, сотрудники = запрос(f"/company/{филиал}/staff", партнёр, токен)
    сколько = len(сотрудники.get("data") or [])
    if код_с != 200 or not сколько:
        завершить(
            f"Филиал {филиал} в списке доступных есть, но сотрудники не пришли\n"
            f"(код {код_с}, {сообщение(сотрудники) or 'ответ пуст'}).\n"
            "Токен записан — перезапустите Директора и посмотрите его журнал.",
            код=2,
        )

    print(f"Проверка: филиал {филиал} отвечает, сотрудников {сколько}.")
    print("\nГотово. Перезапустите Директора:")
    print("    ~/rubl-director/local/Запустить.command")


if __name__ == "__main__":
    main()
