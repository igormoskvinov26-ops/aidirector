"""Какие поля на самом деле приходят в записи YCLIENTS.

Нужен для модуля «Открытие/закрытие смены»: в ТЗ сказано не угадывать имена
полей API, а подтвердить их на реальных ответах.

Три вопроса, без ответа на которые модуль считать нельзя:

1. Есть ли у записи дата СОЗДАНИЯ (не дата визита). От неё зависит показатель
   «создано сегодня на будущие даты».
2. Сколько у клиента выполненных визитов ЗА ВСЮ ИСТОРИЮ. Наша база хранит
   визиты только за окно синхронизации (90 дней назад), а «новый», «повторный»
   и «станет постоянным» считаются по всей жизни клиента: у пришедшего раз в
   полгода в базе будет не то число.
3. Отдаёт ли /records/ историю одного клиента по фильтру client_id. Если да —
   историю можно спросить точечно по тем, кто записан сегодня, и не гадать.

Персональные данные не печатаются. Имя, телефон, почта и комментарии
заменяются на «***»: вывод этого скрипта отправляется в переписку.

Запуск из папки проекта:
    cd backend && uv run python "../scripts/показать-поля-записи.py"
"""

import asyncio
import sys
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "backend"))

from app.api.yclients import YClientsClient  # noqa: E402

# Ключи, значения которых не показываем никогда.
ЛИЧНОЕ = {
    "name", "phone", "email", "comment", "client_comment", "surname",
    "patronymic", "full_name", "display_name", "text", "notes",
}

# Что ищем: как в YCLIENTS может называться дата создания записи.
КАНДИДАТЫ_СОЗДАНИЯ = [
    "create_date", "created_at", "created", "datetime_create", "date_create",
    "creation_date", "created_date", "record_created", "add_date",
]


def значение(ключ: str, знач: object) -> str:
    if ключ.lower() in ЛИЧНОЕ:
        return "***" if знач else "(пусто)"
    if isinstance(знач, (dict, list)):
        return f"<{type(знач).__name__}, {len(знач)} элементов>"
    return repr(знач)


# Как в справочнике клиентов может называться число визитов за всю жизнь.
КАНДИДАТЫ_ВИЗИТОВ = [
    "visits_count", "visit_count", "visits", "visits_total", "records_count",
]


async def справочник_клиентов(client: YClientsClient) -> dict | str:
    """Одна строка из /clients/ — там живут счётчики за всю историю.

    Наша база визитов хранит только окно синхронизации (90 дней назад), а
    «новый», «повторный» и «станет постоянным» считаются по всей жизни
    клиента. Если YCLIENTS отдаёт счётчик визитов в справочнике, считать
    можно по нему и не поднимать всю историю записей.
    """
    try:
        ответ = await client.get_clients(page=1, page_size=1)
    except Exception as сбой:  # noqa: BLE001 — печатаем причину, не падаем
        return f"недоступен: {type(сбой).__name__}: {сбой}"
    строки = ответ.get("data") if isinstance(ответ, dict) else ответ
    if not isinstance(строки, list) or not строки:
        return "адрес ответил, но ни одного клиента не вернул"
    return строки[0]


def печатать_справочник(строка: dict | str) -> None:
    if isinstance(строка, str):
        print(f"  {строка}")
        return
    for ключ in sorted(строка):
        print(f"  {ключ:24} = {значение(ключ, строка[ключ])}")
    найдено = [к for к in КАНДИДАТЫ_ВИЗИТОВ if к in строка]
    print("  ---")
    if найдено:
        for к in найдено:
            print(f"  СЧЁТЧИК ВИЗИТОВ  {к} = {строка[к]!r}")
    else:
        print("  Счётчика визитов за всю историю среди ожидаемых имён нет:")
        print("  " + ", ".join(КАНДИДАТЫ_ВИЗИТОВ))


async def история_клиента(client: YClientsClient, ответ: dict, сегодня: date) -> dict | str:
    """Отдаёт ли /records/ историю одного клиента по фильтру client_id.

    Если фильтр работает, историю можно спросить точечно по тем, кто записан
    сегодня. Если он молча игнорируется, в ответе окажутся чужие записи — это
    и проверяем: считаем, сколько строк принадлежит запрошенному клиенту.
    Молчаливо игнорируемый фильтр опаснее отсутствующего: цифры выйдут
    правдоподобные и неверные.
    """
    записи = ответ.get("data") if isinstance(ответ, dict) else ответ
    if not isinstance(записи, list):
        return "не на чем проверять: записей не получено"
    кому = None
    for з in записи:
        cid = (з.get("client") or {}).get("id")
        if cid:
            кому = int(cid)
            break
    if кому is None:
        return "не на чем проверять: ни у одной записи нет client.id"

    год_назад = сегодня - timedelta(days=365)
    try:
        ответ_истории = await client._get(
            f"/records/{client.company_id}",
            {"start_date": год_назад.isoformat(), "end_date": сегодня.isoformat(),
             "client_id": кому, "count": 50, "page": 1},
        )
    except Exception as сбой:  # noqa: BLE001
        return f"запрос с client_id не прошёл: {type(сбой).__name__}: {сбой}"

    строки = ответ_истории.get("data") if isinstance(ответ_истории, dict) else ответ_истории
    if not isinstance(строки, list):
        return "ответ на запрос с client_id не содержит списка записей"
    свои = sum(1 for з in строки if int((з.get("client") or {}).get("id") or 0) == кому)
    мета = ответ_истории.get("meta") if isinstance(ответ_истории, dict) else None
    всего = (мета or {}).get("total_count") if isinstance(мета, dict) else None
    return {"строк": len(строки), "из них этого клиента": свои,
            "обещано total_count": всего}


def печатать_историю(итог: dict | str) -> None:
    if isinstance(итог, str):
        print(f"  {итог}")
        return
    for ключ, знач in итог.items():
        print(f"  {ключ:24} = {знач!r}")
    строк, свои = итог["строк"], итог["из них этого клиента"]
    if строк and свои == строк:
        print("  ВЫВОД: фильтр client_id работает — историю можно спросить точечно.")
    elif строк:
        print("  ВЫВОД: фильтр игнорируется — в ответе чужие записи, опираться нельзя.")
    else:
        print("  ВЫВОД: ответ пуст — за год у клиента записей нет либо фильтр режет всё.")


async def main() -> None:
    сегодня = date.today()
    # Окно захватывает и прошедшие визиты, и будущие записи: нужны оба вида.
    с, по = сегодня - timedelta(days=7), сегодня + timedelta(days=7)

    async with YClientsClient() as client:
        print(f"Филиал {client.company_id}, записи с {с} по {по}\n")
        # Тот же вызов, которым каждый день ходят «Записи за месяц»
        # (barber_month.pages). Метод get_records() из клиента намеренно НЕ
        # используется: его не вызывает ни один модуль проекта, и имена
        # параметров у него другие (date_from вместо start_date) — проверять
        # поля непроверенным путём значит проверять не то.
        ответ = await client._get(
            f"/records/{client.company_id}",
            {"start_date": с.isoformat(), "end_date": по.isoformat(),
             "count": 50, "page": 1},
        )
        справочник = await справочник_клиентов(client)
        история = await история_клиента(client, ответ, сегодня)

    записи = ответ.get("data") if isinstance(ответ, dict) else ответ
    if not isinstance(записи, list) or not записи:
        print("YCLIENTS не вернул ни одной записи за это окно.")
        print("Ответ целиком (без личных данных):", значение("ответ", ответ))
        sys.exit(1)

    print(f"Получено записей: {len(записи)}\n")

    # 1. Все поля записи — это и есть ответ на «не угадывать имена полей».
    запись = записи[0]
    print("── ПОЛЯ ОДНОЙ ЗАПИСИ ─────────────────────────────")
    for ключ in sorted(запись):
        print(f"  {ключ:24} = {значение(ключ, запись[ключ])}")

    # 2. Главный вопрос: есть ли дата создания.
    print("\n── ДАТА СОЗДАНИЯ ЗАПИСИ ──────────────────────────")
    найдено = [к for к in КАНДИДАТЫ_СОЗДАНИЯ if к in запись]
    if найдено:
        for к in найдено:
            print(f"  ЕСТЬ  {к} = {запись[к]!r}")
    else:
        print("  НЕТ ни одного из ожидаемых имён:")
        print("  " + ", ".join(КАНДИДАТЫ_СОЗДАНИЯ))
        похожие = [к for к in запись if "creat" in к.lower() or "add" in к.lower()]
        print(f"  Похожие по названию поля: {похожие or 'нет'}")

    # 3. Состав услуг и стоимость: подтверждаем cost_to_pay.
    print("\n── ПОЛЯ УСЛУГИ ВНУТРИ ЗАПИСИ ─────────────────────")
    услуги = запись.get("services") or []
    с_услугами = запись if услуги else next(
        (з for з in записи if з.get("services")), None
    )
    if с_услугами and с_услугами.get("services"):
        услуга = с_услугами["services"][0]
        for ключ in sorted(услуга):
            print(f"  {ключ:24} = {значение(ключ, услуга[ключ])}")
    else:
        print("  Ни в одной записи окна нет услуг — показать нечего.")

    # 4. Клиент внутри записи: нужен только стабильный id.
    print("\n── ПОЛЯ КЛИЕНТА ВНУТРИ ЗАПИСИ ────────────────────")
    клиент = запись.get("client")
    if isinstance(клиент, dict):
        for ключ in sorted(клиент):
            print(f"  {ключ:24} = {значение(ключ, клиент[ключ])}")
    else:
        print(f"  client = {значение('client', клиент)}")

    # 5. Статусы посещения: по ним считаются «выполнено» и «не пришёл».
    print("\n── КАКИЕ ВСТРЕЧАЮТСЯ ПРИЗНАКИ ПОСЕЩЕНИЯ ──────────")
    сводка: dict[object, int] = {}
    for з in записи:
        ключ = (з.get("visit_attendance"), з.get("attendance"), з.get("deleted"))
        сводка[ключ] = сводка.get(ключ, 0) + 1
    print("  (visit_attendance, attendance, deleted) → сколько записей")
    for ключ, сколько in sorted(сводка.items(), key=lambda p: -p[1]):
        print(f"  {ключ} → {сколько}")

    # 6. Счётчик визитов за всю историю — в справочнике клиентов.
    print("\n── ПОЛЯ КЛИЕНТА В СПРАВОЧНИКЕ /clients/ ─────────")
    печатать_справочник(справочник)

    # 7. Можно ли спросить историю одного клиента.
    print("\n── ИСТОРИЯ ОДНОГО КЛИЕНТА ПО ФИЛЬТРУ client_id ───")
    печатать_историю(история)

    print("\nГотово. Пришлите этот вывод целиком — по нему настрою расчёты.")


if __name__ == "__main__":
    asyncio.run(main())
